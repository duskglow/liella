#!/usr/bin/env python3
"""Generate crates/legacy/src/sysconf_table.rs from spec/abi/sysconf.tsv (spec §24.4).

The table holds the answers the reference glibc gives from its headers: every sysconf name
whose value does not depend on the machine, and every confstr string. The names computed when
asked (limits, processors, memory, caches, signal stacks) are excluded here and answered by
liella::system (D-24.1); the list below names them.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")

COMPUTED = {
    "_SC_ARG_MAX", "_SC_CHILD_MAX", "_SC_CLK_TCK", "_SC_NGROUPS_MAX", "_SC_OPEN_MAX", "_SC_PAGESIZE",
    "_SC_PAGE_SIZE", "_SC_SIGQUEUE_MAX", "_SC_NPROCESSORS_CONF", "_SC_NPROCESSORS_ONLN", "_SC_PHYS_PAGES",
    "_SC_AVPHYS_PAGES", "_SC_MINSIGSTKSZ", "_SC_SIGSTKSZ", "_SC_THREAD_STACK_MIN",
}


def main():
    rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(ROOT, "spec/abi/sysconf.tsv"), encoding="utf-8")][1:]
    sc, cs = {}, {}
    for kind, name, num, value, err, _varies in rows:
        num = int(num)
        if kind == "sc" and name not in COMPUTED and not name.startswith("_SC_LEVEL"):
            sc.setdefault(num, (name, int(value), int(err)))
        elif kind == "cs":
            cs.setdefault(num, (name, value, int(err)))
    out = ["// @generated by spec/tools/sysconf_table.py from spec/abi/sysconf.tsv. Do not edit.",
           "//! The reference glibc's fixed answers for `sysconf` and `confstr` (spec §24.4).",
           "",
           "/// A fixed `sysconf` answer.",
           "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
           "pub enum Fixed {",
           "    /// The value (-1 meaning \"no limit\" or \"not supported\", without `errno`).",
           "    Value(i64),",
           "    /// `EINVAL`: a name glibc does not answer.",
           "    Invalid,",
           "}",
           "",
           "/// The fixed answer for `sysconf(name)`, if `name` is one; computed names and unknown",
           "/// numbers are `None`.",
           "pub fn sysconf(name: i32) -> Option<Fixed> {",
           "    Some(match name {"]
    for num in sorted(sc):
        name, value, err = sc[num]
        ans = "Fixed::Invalid" if err else f"Fixed::Value({value})"
        out.append(f"        {num} => {ans}, // {name}")
    out += ["        _ => return None,", "    })", "}", "",
            "/// `confstr(name)`'s text, `None` for an unknown name (`EINVAL`).",
            "pub fn confstr(name: i32) -> Option<&'static [u8]> {",
            "    Some(match name {"]
    for num in sorted(cs):
        name, value, err = cs[num]
        if err:
            continue
        out.append(f"        {num} => b\"{value}\", // {name}")
    out += ["        _ => return None,", "    })", "}", ""]
    path = os.path.join(ROOT, "crates/legacy/src/sysconf_table.rs")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"{len(sc)} sysconf names, {len(cs)} confstr names")


if __name__ == "__main__":
    main()
