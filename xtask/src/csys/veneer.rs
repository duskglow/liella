//! The C syscall veneer's source for the process, signal, time, sched, socket and system areas
//! (COLD-REWRITE-W-far-08). Decisions are D-X.25.
//!
//! One wrapper per row of `csys/syscalls.tsv`, and nothing else in the file:
//!
//! * the definition is checked against the prototype in `liella_sys.h` (the same table made
//!   it), so a C wrapper and the Rust declaration of it cannot drift apart unnoticed;
//! * the kernel number comes from `liella_sysnr.h` (the UAPI header's numbers, copied at
//!   generation time) so the build needs no kernel header;
//! * the call is the arity-matched primitive of `liella_raw.h`, a tail call the compiler turns
//!   into register moves, `syscall`, `ret`;
//! * the result is the kernel's own (a value, or `-errno`): nothing at this level narrows,
//!   translates or stores it, and pointers travel as the registers they are.

use super::Call;
use std::fmt::Write as _;

/// The areas whose files this module writes.
pub(super) const AREAS: [&str; 6] = ["process", "signal", "time", "sched", "socket", "system"];

/// A parameter declaration for argument `i` of the table kind `kind`.
fn param(kind: char, i: usize) -> String {
    match kind {
        'c' => format!("const void *a{i}"),
        'p' => format!("void *a{i}"),
        _ => format!("long a{i}"),
    }
}

/// The argument as a register value: integers as they are, pointers cast to `long`.
fn register(kind: char, i: usize) -> String {
    if kind == 'i' {
        format!("a{i}")
    } else {
        format!("(long)a{i}")
    }
}

/// The source of `csys/src/sys/<area>.c` for the calls of that area, in table order.
pub(super) fn unit(area: &str, calls: &[&Call]) -> String {
    let mut s = String::new();
    s.push_str("/* @generated by `cargo xtask csys-gen` from csys/syscalls.tsv. Do not edit. */\n");
    let _ = writeln!(s, "/* Class sys, area `{area}` (spec Appendix A.1). */");
    s.push_str("#include \"liella_sys.h\"\n#include \"liella_sysnr.h\"\n#include \"liella_raw.h\"\n\n");
    s.push_str("_Static_assert(sizeof(void *) == sizeof(long), \"pointers travel as registers: LP64 only\");\n");
    for c in calls {
        let params = if c.args.is_empty() {
            "void".to_string()
        } else {
            c.args.iter().enumerate().map(|(i, k)| param(*k, i)).collect::<Vec<_>>().join(", ")
        };
        // `*` is the generic `syscall`: its first argument is the call number, the rest are the
        // kernel's six.
        let generic = c.nr == "*";
        let mut regs: Vec<String> = Vec::new();
        if !generic {
            regs.push(format!("LIELLA_NR_{}", c.nr));
        }
        regs.extend(c.args.iter().enumerate().map(|(i, k)| register(*k, i)));
        let arity = if generic { c.args.len() - 1 } else { c.args.len() };
        let _ = write!(s, "\nlong liella_sys_{}({params})\n{{\n    return liella_raw{arity}({});\n}}\n", c.name, regs.join(", "));
    }
    s
}
