fn compare_regex(want: &[(String, Vec<String>)], got: &[(String, Vec<String>)], rec: &[(String, Vec<String>)]) {
    let posix = posix_lines();
    let posix_keys: Vec<&String> = posix.keys().collect();
    let mut posix_seen = vec![false; posix_keys.len()];
    let mut known_seen = [false; KNOWN_REGEX.len()];
    let (mut compared, mut diffs) = (0usize, 0usize);
    let mut by_cat: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    for name in REGEX {
        let (w, g, rc) = (section(want, name), section(got, name), section(rec, name));
        assert_eq!(w, rc, "the reference's section {name} differs from the record (patterns.glibc.txt.gz)");
        assert_eq!(w.len(), g.len(), "section {name}: line counts differ");
        let mut locale = String::new();
        for (k, (wl, gl)) in w.iter().zip(g.iter()).enumerate() {
            if let Some(l) = wl.strip_prefix("-- locale ") {
                locale = l.to_string();
            }
            compared += 1;
            let expected: &str = if let Some(i) = KNOWN_REGEX.iter().position(|(loc, ref_line, _, _)| ref_line == wl && locale.contains(loc)) {
                if gl == KNOWN_REGEX[i].2 {
                    known_seen[i] = true;
                    eprintln!("recorded difference ({}):\n  glibc  {wl}\n  liella {gl}", KNOWN_REGEX[i].3);
                }
                KNOWN_REGEX[i].2
            } else if let Some((cats, pl)) = posix.get(wl) {
                if let Some(i) = posix_keys.iter().position(|key| *key == wl) {
                    posix_seen[i] = true;
                }
                for c in cats.split(',') {
                    let (cat, n) = c.split_once(':').unwrap();
                    let e = by_cat.entry(cat.to_string()).or_default();
                    e.0 += 1;
                    e.1 += n.parse::<usize>().unwrap();
                }
                pl
            } else {
                wl
            };
            if gl != expected {
                diffs += 1;
                if diffs <= 40 {
                    eprintln!("section {name} line {}:\n  glibc    {wl}\n  expected {expected}\n  liella   {gl}", k + 1);
                }
            }
        }
    }
    eprintln!("regex lines compared: {compared}; lines (cases) that follow POSIX XBD 9.1 where glibc differs, by category: {by_cat:?}");
    assert_eq!(diffs, 0, "regex lines that differ from the reference, the POSIX reading and the recorded differences");
    for (i, s) in known_seen.iter().enumerate() {
        assert!(s, "recorded difference no longer seen: {:?}", KNOWN_REGEX[i]);
    }
    for (i, s) in posix_seen.iter().enumerate() {
        assert!(s, "a line of regex-posix.expected.txt is not in the reference's output: {}", posix_keys[i]);
    }
}

/// Paths of a `glob` result line, sorted (directory order compared as a set).
fn as_set(line: &str) -> Vec<String> {
    // The last name carries the line's end marker (` $`), which is not part of the name.
    let mut v: Vec<String> = line.split(" [").skip(2).map(|s| s.trim_end_matches(" $").to_string()).collect();
    v.sort();
    v
}

/// The walk of the pattern `tree/*/*` aborts at the unreadable directory (`tree/noread`; with
/// `GLOB_ERR`, or because the error callback the probe installs returns non-zero). Whether
/// `GLOB_MAGCHAR` is set in the abandoned result depends on whether the walk had already finished
/// a directory with matches before it reached `noread`, which is the directory order of the
/// scratch file system (hash order on ext4, newest first on tmpfs; probed 2026-10-21). The record
/// was made on ext4, so the reference is compared with it ignoring that one flag. Liella's line is
/// compared with the reference's of the same run with the same flag set aside (glob(3) says
/// nothing about the flags of a failed call; Liella reports 0 on both file systems); every other
/// field stays exact.
fn order_dependent_magchar(line: &str) -> bool {
    line.starts_with("glob [tree/*/*] ") && line.contains(" -> 2 pathc=0 ")
}

fn compare_other(want: &[(String, Vec<String>)], got: &[(String, Vec<String>)], rec: &[(String, Vec<String>)], mode: &str) {
    let mut known_seen = vec![false; KNOWN.len()];
    let (mut compared, mut diffs, mut fc_diffs) = (0usize, 0usize, 0usize);
    let fs_line = section(want, "glob").iter().find(|l| l.starts_with("fs:")).cloned().unwrap_or_default();
    for name in OTHER {
        let (w, g, rc) = (section(want, name), section(got, name), section(rec, name));
        assert_eq!(w.len(), g.len(), "section {name}: line counts differ ({mode})");
        assert_eq!(w.len(), rc.len(), "section {name}: the reference's line count differs from the record");
        for (wl, rl) in w.iter().zip(rc.iter()) {
            if wl != rl {
                let ordered = name == "glob" && wl.contains("NOSORT");
                let aborted = name == "glob" && order_dependent_magchar(wl) && order_dependent_magchar(rl) && wl.replace("magchar=1", "magchar=0") == rl.replace("magchar=1", "magchar=0");
                assert!(ordered && as_set(wl) == as_set(rl) || aborted || wl.starts_with("fs:"), "the reference's section {name} differs from the record:\n  record    {rl}\n  reference {wl}");
            }
        }
        let mut locale = String::new();
        let mut subjects: Vec<Vec<u8>> = Vec::new();
        for (k, (wl, gl)) in w.iter().zip(g.iter()).enumerate() {
            compared += 1;
            if let Some(l) = wl.strip_prefix("-- locale ") {
                locale = l.to_string();
            }
            if let Some(list) = wl.strip_prefix("subjects ") {
                subjects = list.split(' ').map(|s| s.trim_start_matches('[').trim_end_matches(']').as_bytes().to_vec()).collect();
            }
            let multibyte = locale.contains("UTF-8");
            let known = KNOWN.iter().position(|(s, ref_line, _, _)| *s == name && ref_line == wl && (multibyte || !MULTIBYTE_ONLY.contains(ref_line)));
            let expected: String = if let Some(i) = known {
                if gl == KNOWN[i].2 {
                    known_seen[i] = true;
                    if mode == "on" || mode == "plain" {
                        eprintln!("recorded difference ({}):\n  glibc  {wl}\n  liella {gl}", KNOWN[i].3);
                    }
                }
                KNOWN[i].2.to_string()
            } else if wl.starts_with("fc ") && wl != gl {
                let r = reference_fc(wl, &subjects);
                assert_ne!(&r, wl, "fc line where Liella differs but fnmatch(3)'s definition agrees with glibc: {wl}");
                fc_diffs += 1;
                r
            } else {
                wl.clone()
            };
            // The flag of an aborted `tree/*/*` walk is the reference's directory order (see
            // [`order_dependent_magchar`]); glob(3) says nothing about the flags of a failed call, so Liella's
            // value there is compared with the reference's with that one flag set aside.
            let unflagged = |l: &str| if name == "glob" && order_dependent_magchar(wl) { l.replace("magchar=1", "magchar=0") } else { l.to_string() };
            if unflagged(gl) != unflagged(&expected) {
                diffs += 1;
                if diffs <= 40 {
                    let order = if name == "glob" && wl.contains("NOSORT") { format!(" (directory order of the scratch file system, {fs_line})") } else { String::new() };
                    eprintln!("section {name} line {}{order}:\n  glibc    {wl}\n  expected {expected}\n  liella   {gl}", k + 1);
                }
            }
        }
    }
    eprintln!("fnmatch/glob/wordexp lines compared ({mode}): {compared}; fc lines that follow fnmatch(3)'s FNM_PERIOD where glibc differs ({FNM_PERIOD_FC}): {fc_diffs}; directory-order lines compared on the scratch file system ({fs_line})");
    assert_eq!(diffs, 0, "fnmatch/glob/wordexp lines that differ from the reference and the recorded differences ({mode})");
    for (i, s) in known_seen.iter().enumerate() {
        assert!(s, "recorded difference no longer seen ({mode}): {:?}", KNOWN[i]);
    }
}

#[test]
fn patterns_equal_the_reference() {
    // Clauses: s14_7_c_0, s14_7_c_1, s14_7_c_2, s14_7_c_2_1, s14_7_c_2_2, s14_7_c_2_3, s14_7_c_2_4, s14_7_c_2_5,
    // s14_7_c_2_6, s14_7_g_0, s14_7_f_0, s14_8_c_0, s14_8_c_1, s14_8_c_2, s14_8_c_2_1, s14_8_c_2_2,
    // s14_8_c_2_3, s14_8_c_3, s14_8_c_4, s14_8_f_0, s14_9_c_1, s14_9_c_1_1, s14_9_c_1_2, s14_9_c_1_3,
    // s14_9_c_2, s14_9_c_3, s14_9_g_0, s14_9_f_0, s14_10_c_0, s14_10_c_1, s14_10_c_2, s14_10_c_3, s14_10_c_4,
    // s14_10_f_0 (D-14.4, D-14.5, D-14.7).
    let r = root();
    assert!(r.join("target/liella/libc.a").exists(), "the products are missing: run `cargo xtask so`");
    if skip_note::missing("cc") {
        skip_note::skipped("skipped: no C compiler");
        return;
    }
    if Command::new("localedef").arg("--help").output().is_err() {
        skip_note::skipped("skipped: no localedef (the probe compiles its locales)");
        return;
    }
    let dir = r.join("target/test-oracles");
    std::fs::create_dir_all(&dir).unwrap();
    let (host, ours) = (dir.join("patterns_diff_host"), dir.join("patterns_diff_liella"));
    assert!(build(&host, false), "patterns_diff.c does not build against the host C library");
    assert!(build(&ours, true), "patterns_diff.c does not link against the products");
    let script = r.join("crates/core/tests/oracle/patterns_run.sh");
    let wrap = r.join("crates/core/tests/oracle/nscache_mode.sh");
    let run = |exe: &Path, scratch: &str, mode: Option<&str>| -> String {
        let mut cmd = Command::new("timeout");
        cmd.arg(timeout::secs(1500));
        if let Some(m) = mode {
            cmd.arg("sh").arg(&wrap).arg(m);
        }
        let o = cmd.arg("sh").arg(&script).arg(exe).arg(dir.join(scratch)).env_clear().env("PATH", "/usr/bin:/bin").output().unwrap();
        assert!(o.status.success(), "{} failed: {:?}\n{}", exe.display(), o.status, String::from_utf8_lossy(&o.stderr));
        o.stdout.iter().map(|&b| char::from(b)).collect()
    };
    let mut want = sections(&run(&host, "patterns-host", None));
    env_norm(&mut want);
    let rec = sections(&record());
    let modes: Vec<Option<&str>> = if Command::new("sudo").args(["-n", "true"]).status().is_ok_and(|s| s.success()) {
        vec![Some("on"), Some("off")]
    } else {
        eprintln!("note: no passwordless sudo; Liella runs once, with the name-service cache as configured");
        vec![None]
    };
    for mode in modes {
        let label = mode.unwrap_or("plain");
        eprintln!("name-service cache {label}");
        let mut got = sections(&run(&ours, &format!("patterns-liella-{label}"), mode));
        env_norm(&mut got);
        let names = |s: &[(String, Vec<String>)]| s.iter().map(|(n, _)| n.clone()).collect::<Vec<_>>();
        assert_eq!(names(&want), names(&got), "the sections differ");
        for (name, _) in &want {
            assert!(REGEX.contains(&name.as_str()) || OTHER.contains(&name.as_str()), "section {name} is not compared");
        }
        compare_regex(&want, &got, &rec);
        compare_other(&want, &got, &rec, label);
    }
}
