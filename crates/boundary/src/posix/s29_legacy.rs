/// `struct XDR` (the historical `<rpc/xdr.h>` layout, 48 bytes on x86_64).
#[repr(C)]
#[derive(Debug)]
pub struct Xdr {
    /// `x_op`: `XDR_ENCODE`, `XDR_DECODE` or `XDR_FREE`.
    pub x_op: c_int,
    /// `x_ops`: the stream's operations.
    pub x_ops: *const XdrOps,
    /// `x_public`: the user's (untouched by the memory stream).
    pub x_public: *mut c_char,
    /// `x_private`: the memory stream's current byte.
    pub x_private: *mut c_char,
    /// `x_base`: the memory stream's first byte.
    pub x_base: *mut c_char,
    /// `x_handy`: the memory stream's bytes left.
    pub x_handy: c_uint,
}

/// `struct xdr_ops` (the historical layout: ten entries, the two `int32` ones last).
#[repr(C)]
#[derive(Debug)]
#[allow(missing_docs)]
pub struct XdrOps {
    pub x_getlong: Option<extern "C" fn(*mut Xdr, *mut c_long) -> c_int>,
    pub x_putlong: Option<extern "C" fn(*mut Xdr, *const c_long) -> c_int>,
    pub x_getbytes: Option<extern "C" fn(*mut Xdr, *mut c_char, c_uint) -> c_int>,
    pub x_putbytes: Option<extern "C" fn(*mut Xdr, *const c_char, c_uint) -> c_int>,
    pub x_getpostn: Option<extern "C" fn(*const Xdr) -> c_uint>,
    pub x_setpostn: Option<extern "C" fn(*mut Xdr, c_uint) -> c_int>,
    pub x_inline: Option<extern "C" fn(*mut Xdr, c_uint) -> *mut i32>,
    pub x_destroy: Option<extern "C" fn(*mut Xdr)>,
    pub x_getint32: Option<extern "C" fn(*mut Xdr, *mut i32) -> c_int>,
    pub x_putint32: Option<extern "C" fn(*mut Xdr, *const i32) -> c_int>,
}

/// `xdrproc_t`: a filter, called by `xdr_free` with the object only.
pub type XdrProc = Option<extern "C" fn(*mut Xdr, *mut c_void, ...) -> c_int>;

/// The memory stream's table: one for both directions (the probe: encode and decode streams
/// share it).
static MEM_OPS: XdrOps = XdrOps {
    x_getlong: Some(mem_getlong),
    x_putlong: Some(mem_putlong),
    x_getbytes: Some(mem_getbytes),
    x_putbytes: Some(mem_putbytes),
    x_getpostn: Some(mem_getpostn),
    x_setpostn: Some(mem_setpostn),
    x_inline: Some(mem_inline),
    x_destroy: Some(mem_destroy),
    x_getint32: Some(mem_getint32),
    x_putint32: Some(mem_putint32),
};

// --- the memory stream -------------------------------------------------------------------

/// Claims `n` bytes of a memory stream: the current byte, then the stream moves past them. A miss
/// changes nothing.
// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn mem_take(x: *mut Xdr, n: c_uint) -> Option<*mut c_char> {
    // UNSAFE(slice) SAFETY: x is the caller's memory stream, valid and unaliased for the call.
    let xr = unsafe { &mut *x };
    let left = rules::take(xr.x_handy, n)?;
    let at = xr.x_private;
    // UNSAFE(slice) SAFETY: x_private has x_handy >= n bytes after it (xdrmem_create's contract,
    // §29.1; rules::take checked n), so the result stays within the buffer or one past it.
    xr.x_private = unsafe { at.add(rules::count(n)) };
    xr.x_handy = left;
    Some(at)
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn mem_get_word(x: *mut Xdr) -> Option<u32> {
    // UNSAFE(slice) SAFETY: mem_take granted 4 bytes at the pointer.
    mem_take(x, 4).map(|at| u32::from_be_bytes(unsafe { at.cast::<[u8; 4]>().read_unaligned() }))
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn mem_put_word(x: *mut Xdr, w: u32) -> c_int {
    // UNSAFE(slice) SAFETY: mem_take granted 4 bytes at the pointer.
    c_int::from(mem_take(x, 4).map(|at| unsafe { at.cast::<[u8; 4]>().write_unaligned(w.to_be_bytes()) }).is_some())
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_getlong(x: *mut Xdr, lp: *mut c_long) -> c_int {
    // UNSAFE(slice) SAFETY: lp is the caller's long (x_getlong's contract).
    c_int::from(mem_get_word(x).map(|w| unsafe { lp.write(rules::long_from_wire(w)) }).is_some())
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_putlong(x: *mut Xdr, lp: *const c_long) -> c_int {
    // The low 32 bits go out unchecked (the probe: 0x1ffffffff writes ffffffff); range checks
    // belong to the filters.
    // UNSAFE(slice) SAFETY: lp is the caller's long (x_putlong's contract).
    mem_put_word(x, rules::low32(unsafe { lp.read() }))
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_getint32(x: *mut Xdr, ip: *mut i32) -> c_int {
    // UNSAFE(slice) SAFETY: ip is the caller's int32_t (x_getint32's contract).
    c_int::from(mem_get_word(x).map(|w| unsafe { ip.write(rules::i32_of_word(w)) }).is_some())
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_putint32(x: *mut Xdr, ip: *const i32) -> c_int {
    // UNSAFE(slice) SAFETY: ip is the caller's int32_t (x_putint32's contract).
    mem_put_word(x, rules::word_of_i32(unsafe { ip.read() }))
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_getbytes(x: *mut Xdr, addr: *mut c_char, len: c_uint) -> c_int {
    // UNSAFE(slice) SAFETY: mem_take granted len bytes; addr has room for len (x_getbytes's contract).
    c_int::from(mem_take(x, len).map(|at| unsafe { ptr::copy_nonoverlapping(at, addr, rules::count(len)) }).is_some())
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_putbytes(x: *mut Xdr, addr: *const c_char, len: c_uint) -> c_int {
    // UNSAFE(slice) SAFETY: mem_take granted len bytes; addr holds len (x_putbytes's contract).
    c_int::from(mem_take(x, len).map(|at| unsafe { ptr::copy_nonoverlapping(addr, at, rules::count(len)) }).is_some())
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_getpostn(x: *const Xdr) -> c_uint {
    // UNSAFE(slice) SAFETY: x is the caller's memory stream.
    let xr = unsafe { &*x };
    // UNSAFE(slice) SAFETY: both pointers are in the stream's buffer, x_private at or after x_base.
    let off = unsafe { xr.x_private.offset_from(xr.x_base) };
    // The offset lies in 0..=size and size is a c_uint, so the conversion is exact.
    c_uint::try_from(off).unwrap_or(c_uint::MAX)
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_setpostn(x: *mut Xdr, pos: c_uint) -> c_int {
    let Some(left) = rules::seek(mem_getpostn(x), unsafe_handy(x), pos) else { return 0 };
    // UNSAFE(slice) SAFETY: x is the caller's memory stream, valid and unaliased for the call.
    let xr = unsafe { &mut *x };
    // UNSAFE(slice) SAFETY: rules::seek kept pos within the buffer's end (the end included).
    xr.x_private = unsafe { xr.x_base.add(rules::count(pos)) };
    xr.x_handy = left;
    1
}

// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn unsafe_handy(x: *const Xdr) -> c_uint {
    // UNSAFE(slice) SAFETY: x is a memory stream (the caller's XDR).
    unsafe { (*x).x_handy }
}

#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn mem_inline(x: *mut Xdr, len: c_uint) -> *mut i32 {
    mem_take(x, len).map_or(ptr::null_mut(), |at| at.cast())
}

extern "C" fn mem_destroy(_x: *mut Xdr) {}

