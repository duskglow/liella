crate::internal_entry! {
/// `xdr_opaque`: `cnt` bytes then zero padding to a unit; decode skips the padding unread.
pub extern "C" fn liella_compat_xdr_opaque(x: *mut Xdr, cp: *mut c_char, cnt: c_uint) -> c_int {
    if cnt == 0 {
        return 1;
    }
    let pad = rules::pad(cnt);
    let mut crud: [c_char; 4] = [0; 4];
    match op(x) {
        XDR_DECODE => c_int::from(get_bytes(x, cp, cnt) && (pad == 0 || get_bytes(x, crud.as_mut_ptr(), pad))),
        XDR_ENCODE => c_int::from(put_bytes(x, cp, cnt) && (pad == 0 || put_bytes(x, crud.as_ptr(), pad))),
        XDR_FREE => 1,
        _ => 0,
    }
}}

crate::internal_entry! {
/// `xdr_bytes`: a length word (checked against `maxsize` after it went through the stream), then
/// opaque data; decode allocates when `*cpp` is NULL; free releases it.
pub extern "C" fn liella_compat_xdr_bytes(x: *mut Xdr, cpp: *mut *mut c_char, sizep: *mut c_uint, maxsize: c_uint) -> c_int {
    if liella_compat_xdr_u_int(x, sizep) == 0 {
        return 0;
    }
    let o = op(x);
    // UNSAFE(slice) SAFETY: sizep is the caller's length (xdr_bytes's contract).
    let n = unsafe { sizep.read() };
    // UNSAFE(slice) SAFETY: cpp is the caller's pointer slot (xdr_bytes's contract).
    let sp = unsafe { cpp.read() };
    if o != XDR_FREE && !rules::len_ok(n, maxsize) {
        return 0;
    }
    match o {
        XDR_DECODE if n == 0 => 1,
        XDR_DECODE => {
            let Some(sp) = target(cpp, sp, n) else { return 0 };
            liella_compat_xdr_opaque(x, sp, n)
        }
        XDR_ENCODE => liella_compat_xdr_opaque(x, sp, n),
        XDR_FREE => release(cpp, sp),
        _ => 0,
    }
}}

/// The decode target: the caller's buffer, or `n` new bytes stored in `*cpp`.
// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn target(cpp: *mut *mut c_char, sp: *mut c_char, n: c_uint) -> Option<*mut c_char> {
    if !sp.is_null() {
        return Some(sp);
    }
    let fresh = heap::malloc_entry(rules::count(n)).cast::<c_char>();
    if fresh.is_null() {
        return None;
    }
    // UNSAFE(slice) SAFETY: cpp is the caller's pointer slot.
    unsafe { cpp.write(fresh) };
    Some(fresh)
}

/// The free direction: releases `*cpp` (when set) and clears it.
// UNSAFE(slice): the stream, its buffer and the objects are C pointers (§29.1).
#[allow(unsafe_code)]
fn release(cpp: *mut *mut c_char, sp: *mut c_char) -> c_int {
    if !sp.is_null() {
        heap::free_entry(sp.expose_provenance());
        // UNSAFE(slice) SAFETY: cpp is the caller's pointer slot.
        unsafe { cpp.write(ptr::null_mut()) };
    }
    1
}

crate::internal_entry! {
/// `xdr_string`: a length word, the bytes and padding; encode of NULL fails; a length above
/// `maxsize` fails after the length word; decode allocates length + 1 when `*cpp` is NULL and
/// ends the string with a NUL; free releases it.
pub extern "C" fn liella_compat_xdr_string(x: *mut Xdr, cpp: *mut *mut c_char, maxsize: c_uint) -> c_int {
    let o = op(x);
    // UNSAFE(slice) SAFETY: cpp is the caller's pointer slot (xdr_string's contract).
    let sp = unsafe { cpp.read() };
    let mut size: c_uint = 0;
    match o {
        XDR_FREE => return release(cpp, sp),
        XDR_ENCODE if sp.is_null() => return 0,
        // A string longer than UINT32_MAX bytes has no XDR length and fails (not probed).
        // UNSAFE(slice) SAFETY: an encoded string is NUL-terminated (the contract).
        XDR_ENCODE => match c_uint::try_from(unsafe { CStr::from_ptr(sp) }.count_bytes()) {
            Ok(n) => size = n,
            Err(_) => return 0,
        },
        _ => {}
    }
    if liella_compat_xdr_u_int(x, &mut size) == 0 {
        return 0;
    }
    let Some(room) = rules::string_room(size, maxsize) else { return 0 };
    match o {
        XDR_DECODE => {
            let Some(sp) = target(cpp, sp, room) else { return 0 };
            // UNSAFE(slice) SAFETY: the target holds room = size + 1 bytes, so byte `size` is in it.
            let end = unsafe { sp.add(rules::count(size)) };
            // UNSAFE(slice) SAFETY: end is the target's last byte (above).
            unsafe { end.write(0) };
            liella_compat_xdr_opaque(x, sp, size)
        }
        _ => liella_compat_xdr_opaque(x, sp, size),
    }
}}

crate::internal_entry! {
/// `xdr_wrapstring`: `xdr_string` without a bound.
pub extern "C" fn liella_compat_xdr_wrapstring(x: *mut Xdr, cpp: *mut *mut c_char) -> c_int {
    liella_compat_xdr_string(x, cpp, c_uint::MAX)
}}

crate::internal_entry! {
/// `xdr_free`: runs `proc` over `objp` on a stream in the free direction.
pub extern "C" fn liella_compat_xdr_free(proc_: XdrProc, objp: *mut c_char) {
    let mut x = Xdr { x_op: XDR_FREE, x_ops: ptr::null(), x_public: ptr::null_mut(), x_private: ptr::null_mut(), x_base: ptr::null_mut(), x_handy: 0 };
    if let Some(f) = proc_ {
        // Proc is the caller's filter for objp's type (xdr_free's contract).
        f(&mut x, objp.cast());
    }
}}

