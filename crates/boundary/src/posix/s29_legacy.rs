//! Translation for spec §29: legacy and compatibility subsystems.
//!
//! §29.1 XDR primitives and the memory stream (LG-12). glibc 2.39 exports every `xdr_*` name only
//! as a compat version (`xdr_int@GLIBC_2.2.5`, `xdr_quad_t@GLIBC_2.3.4`), so the translations are
//! internal `liella_compat_*` entries (local in `libc.so.6`, R15-1, R15-2); the `.symver` aliases
//! that give them their versions come from the compat generator (LG-1). The filters reach the
//! stream only through its `x_ops` table, as callers' own streams require; the rules they apply
//! (ranges, padding, lengths, room) are `liella_legacy::sunrpc`. Behaviour record:
//! `spec/behaviour/xdr.md`.
//!
//! Implementation phase: 15 (implementation-plan.md §6). So far the STREAMS names (§29.3) and
//! `sysctl`/`__sysctl` (§29.4), with `bdflush` and `sstk` (§24.6, LEGACY-STUBS).
//!
//! Every name here is compat-only (`name@GLIBC_2.2.5`, no default version in 2.39): the
//! translation is exported as `liella_compat_<name>` and a `.symver` stub in
//! `csys/src/machine/compat_aliases.S` (generated by `cargo xtask compat-gen` from the `behaviour`
//! and `stub` rows of `spec/abi/compat-plan.tsv`) gives it the non-default version, so a program linked anew
//! never binds it and `libc.a` does not hold it (R15-1, R15-2). Tests call the Rust functions.

