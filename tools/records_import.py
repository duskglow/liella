#!/usr/bin/env python3
"""Convert the hand-written registry tables into records (RECORDS-1), and prove the conversion.

Python 3 standard library only. Run from the tree root.

  tools/records_import.py                     convert: write records/ (one file per row), the views' head and
                                              tail files and records/views.toml, from today's tables
  tools/records_import.py --verify [--base R] the conversion proof: every view generated by
                                              `cargo xtask records-gen` equals the table at R (default origin/next)
                                              except the documented normalisations, which it lists by file and line
  tools/records_import.py --from-diff B BR    convert the rows a pre-cutover branch BR added to the tables
                                              (diff B...BR) into records

The importer and the Rust renderer (xtask/src/records/) are two independent implementations: --verify parses the
old tables here and the generated views on disk, and compares row by row.
"""

import collections
import os
import re
import subprocess
import sys

GENERATED = "<!-- @generated by `cargo xtask records-gen` from records/; edit the records, never this file -->"
DECISION_DIR = "plan/07-decisions"
NOT_A_TABLE = {"x3-regex-lazy-dfa.md"}
COMPAT_PATH = "docs/compat-flags.md"
SAT_DIR = "docs/saturation"
SAT_INDEX = "docs/saturation-register.md"
SAT_TABLE_SECTIONS = range(1, 8)

DECISION_COLUMNS = {"ID": "id", "Spec": "spec", "Ann.": "ann", "Pattern": "pattern", "Decision": "body"}
COMPAT_COLUMNS = ["id", "behaviour", "glibc", "liella", "restore", "cost", "status"]
SAT8_COLUMNS = ["row", "now", "limit", "reason_class", "basis", "source", "tried", "flag"]
SAT3_COLUMNS = ["row", "now", "open"]
COMPAT_STATUS = ("registered", "implemented", "partial", "withdrawn")

KEYS = {
    "decision": ["id", "series", "section", "spec", "ann", "pattern", "status", "supersedes", "amends", "story", "date", "tests", "body"],
    "compat": ["id", "behaviour", "glibc", "liella", "restore", "cost", "status", "status_text", "decisions", "story", "date", "body"],
    "saturation": ["id", "section", "row", "now", "limit", "reason_class", "basis", "source", "tried", "flag", "open", "status", "supersedes", "story", "date", "body"],
}


def die(msg):
    print(f"records_import: {msg}", file=sys.stderr)
    sys.exit(1)


# ---- ids and their order (the same key as xtask/src/records/schema.rs) ----

ID_RE = re.compile(r"^(D-(?:[1-9][0-9]*|X|C0|T)\.|D-H|COMPAT-|SR-)([0-9]+)([a-z]?)$")


def series_of(rid):
    m = ID_RE.match(rid)
    if not m:
        die(f"not an id: {rid!r}")
    return m.group(1).rstrip(".-")


def id_key(rid, series_order):
    m = ID_RE.match(rid)
    s = m.group(1).rstrip(".-")
    return (series_order.index(s) if s in series_order else len(series_order), int(m.group(2)), m.group(3))


def default_series_order(series):
    num = sorted((s for s in series if re.fullmatch(r"D-[0-9]+", s)), key=lambda s: int(s[2:]))
    rest = [s for s in series if s not in num]  # first-appearance order (D-H before D-T)
    return num + rest


# ---- tables ----

class Table:
    """A file split into head (text before the header row), header, separator, rows (line number, text), the
    lines inside the table that are not rows (strays), and tail (text after the last row)."""

    def __init__(self, path, text, row_prefix):
        self.path = path
        lines = text.split("\n")
        hdr = None
        for i in range(len(lines) - 1):
            if lines[i].startswith("| ") and re.match(r"^\|[-:| ]+\|$", lines[i + 1]):
                hdr = i
                break
        if hdr is None:
            die(f"{path}: no table")
        self.head = "".join(line + "\n" for line in lines[:hdr])
        self.header, self.separator = lines[hdr], lines[hdr + 1]
        body = lines[hdr + 2:]
        if row_prefix is None:  # the table ends at its first line that is not a row
            last = next((k for k, line in enumerate(body) if not line.startswith("|")), len(body)) - 1
        else:  # the table ends at its last row; anything between rows is a stray line
            last = max((k for k, line in enumerate(body) if line.startswith(row_prefix)), default=-1)
        self.rows, self.strays = [], []
        for k in range(last + 1):
            (self.rows if body[k].startswith("| ") and (row_prefix is None or body[k].startswith(row_prefix)) else self.strays).append((hdr + 3 + k, body[k]))
        self.tail = "\n".join(body[last + 1:])

    def cells(self, line, n, line_no=None):
        if not (line.startswith("| ") and line.endswith(" |")):
            die(f"{self.path}: row not in `| cell | cell |` form: {line[:80]}")
        inner = line[2:-2]
        while " | | " in inner:
            # Normalisation (f): an empty cell written `| |` renders as `|  |` (the one spelling of an empty cell).
            inner = inner.replace(" | | ", " |  | ", 1)
            if line_no is not None:
                ESCAPES.append(("f", f"{self.path}:{line_no}: empty cell `| |` written `|  |`"))
        cells = inner.split(" | ", n - 1)
        if len(cells) != n or cells[0] == "":
            die(f"{self.path}: row has {len(cells)} cells, the view has {n}, or no first cell: {line[:80]}")
        return cells


def decision_view_name(fname):
    stem = fname[:-3]
    if stem.startswith("00-"):
        return "h"
    if stem.startswith("c0-"):
        return "c0"
    if stem.startswith("x-"):
        return "x"
    m = re.match(r"^(s[0-9]{2}(?:-[0-9]{2})?)", stem)
    if not m:
        die(f"{fname}: no section name")
    return m.group(1)


def sat_files(root):
    out = {}
    for f in sorted(os.listdir(os.path.join(root, SAT_DIR))):
        m = re.match(r"^([0-9]+)-.*\.md$", f)
        if m:
            out[int(m.group(1))] = f
    return out


def views_of(root):
    """Every view: dict(name, path, kind, section, columns, row_prefix)."""
    views = []
    for f in sorted(os.listdir(os.path.join(root, DECISION_DIR))):
        if f.endswith(".md") and f not in NOT_A_TABLE:
            n = decision_view_name(f)
            views.append(dict(name=n, path=f"{DECISION_DIR}/{f}", kind="decision", section=n, row_prefix="| D-"))
    views.append(dict(name="compat-flags", path=COMPAT_PATH, kind="compat", section=None, row_prefix="| COMPAT-"))
    files = sat_files(root)
    for n in SAT_TABLE_SECTIONS:
        views.append(dict(name=f"saturation-{n}", path=f"{SAT_DIR}/{files[n]}", kind="saturation", section=str(n), row_prefix=None))
    return views


def columns_for(view, table):
    names = [c.strip() for c in table.header[1:-1].split("|")]
    if view["kind"] == "decision":
        try:
            return [DECISION_COLUMNS[c] for c in names]
        except KeyError as e:
            die(f"{view['path']}: unknown column {e}")
    if view["kind"] == "compat":
        return COMPAT_COLUMNS
    return SAT8_COLUMNS if len(names) == 8 else SAT3_COLUMNS if len(names) == 3 else die(f"{view['path']}: {len(names)} columns")


# ---- canonical TOML subset (the same spelling as xtask/src/records/toml.rs writes) ----

def basic(s):
    if any((ord(c) < 0x20 and c != "\t") or ord(c) == 0x7f for c in s):
        die(f"control character in {s[:60]!r}")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def value(v):
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(basic(x) for x in v) + "]"
    return basic(v)


def record_text(kind, fields):
    out = []
    for k in KEYS[kind]:
        if k == "body":
            body = fields.get("body", "")
            if "'''" in body:
                die(f"{fields['id']}: body contains '''")
            out.append("body = '''\n" + (body + "\n" if body else "") + "'''\n")
        elif k in fields and fields[k] not in (None, []):
            out.append(f"{k} = {value(fields[k])}\n")
    unknown = set(fields) - set(KEYS[kind])
    if unknown:
        die(f"{fields['id']}: unknown keys {sorted(unknown)}")
    return "".join(out)


def record_path(kind, rid):
    if kind == "decision":
        return f"records/decisions/{series_of(rid)}/{rid}.toml"
    return f"records/{kind}/{rid}.toml"


def cell_problems(cell):
    if "\n" in cell or "'''" in cell:
        return "newline or '''"
    if re.search(r"(?<!\\)\|", cell):
        return "unescaped |"
    return None


# ---- conversion ----

ESCAPES = []  # normalisation (e) of the last parse_all: (file:line, what)


def parse_all(root, read):
    """Parse every view source with `read(path) -> text`. Returns [(view, table, columns, records)]."""
    out = []
    problems = []
    escapes = ESCAPES
    escapes.clear()
    sr = 0
    for v in views_of(root):
        t = Table(v["path"], read(v["path"]), v["row_prefix"])
        cols = columns_for(v, t)
        recs = []
        for line_no, line in t.rows:
            cells = t.cells(line, len(cols), line_no)
            for j, c in enumerate(cells):
                if re.search(r"[\x01-\x08]", c):
                    # Normalisation (g): a raw control byte 1..8 is a `\1`..`\8` back-reference that a shell `echo -e`
                    # or `printf` turned into the byte (COMPAT-4's `(a*)*\1`); TOML cannot hold the byte unescaped.
                    c = cells[j] = re.sub(r"[\x01-\x08]", lambda m: "\\" + str(ord(m.group(0))), c)
                    escapes.append(("g", f"{v['path']}:{line_no}: control byte written as the back-reference `\\N` it was in column {cols[j]}"))
                if cell_problems(c) == "unescaped |":
                    # Normalisation (e): GitHub splits a cell at a bare `|`, even inside a code span; `\|` is the
                    # escape the renderer stores verbatim.
                    cells[j] = re.sub(r"(?<!\\)\|", r"\\|", c)
                    escapes.append(("e", f"{v['path']}:{line_no}: bare `|` escaped as `\\|` in column {cols[j]}"))
                p = cell_problems(cells[j])
                if p:
                    problems.append(f"{v['path']}:{line_no}: cell has {p}")
            line = "| " + " | ".join(cells) + " |"
            f = dict(zip(cols, cells))
            if v["kind"] == "decision":
                f["section"] = v["section"]
                f["status"] = "active"
            elif v["kind"] == "compat":
                st = f["status"]
                if st not in COMPAT_STATUS:
                    f["status_text"] = st
                    low = st.lower()
                    f["status"] = "withdrawn" if low.startswith("withdrawn") else "partial" if "registered" in low and ("resolved" in low or "implemented" in low) else die(f"{v['path']}:{line_no}: status {st!r}")
            else:
                sr += 1
                f = dict(id=f"SR-{sr}", section=v["section"], **f, status="active")
            f.setdefault("body", "")  # the Decision cell; compat and saturation rows have no notes yet
            recs.append((line_no, line, f))
        out.append((v, t, cols, recs))
    if problems:
        die("cells the renderer cannot store verbatim:\n  " + "\n  ".join(problems))
    return out


def toml_views(parsed, root):
    out = []
    for v, t, cols, recs in parsed:
        series = default_series_order(list(dict.fromkeys(series_of(r[2]["id"]) for r in recs)))
        ent = [("name", v["name"]), ("path", v["path"]), ("kind", v["kind"])]
        if v["section"] is not None:
            ent.append(("section", v["section"]))
        ent += [("series", series), ("header", t.header), ("separator", t.separator), ("columns", cols)]
        ent.append(("head", f"records/views/{v['name']}.head.md"))
        if t.tail:
            ent.append(("tail", f"records/views/{v['name']}.tail.md"))
        out.append(ent)
    idx = Index(read_file(root, SAT_INDEX), SAT_INDEX)
    out.append([("name", "saturation-register"), ("path", SAT_INDEX), ("kind", "index"), ("dir", SAT_DIR), ("head", "records/views/saturation-register.head.md")] + ([("tail", "records/views/saturation-register.tail.md")] if idx.tail else []))
    return out, idx


def write(root, rel, text):
    p = os.path.join(root, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def read_file(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8", newline="") as fh:
        return fh.read()


class Index:
    """docs/saturation-register.md: head (through the section-0 line), the per-section lines, tail."""

    LINE = re.compile(r"^- \[(.*)\]\(saturation/(([0-9]+)-[^)]*)\): section ([0-9]+)$")

    def __init__(self, text, path):
        lines = text.split("\n")
        first = next(i for i, line in enumerate(lines) if (m := self.LINE.match(line)) and int(m.group(3)) >= 1)
        last = max(i for i, line in enumerate(lines) if self.LINE.match(line))
        self.head = "".join(line + "\n" for line in lines[:first])
        self.entries, self.strays = [], []
        for i in range(first, last + 1):
            m = self.LINE.match(lines[i])
            if m:
                self.entries.append((i + 1, int(m.group(3)), m.group(2), m.group(1)))
            else:
                self.strays.append((i + 1, lines[i]))
        self.tail = "\n".join(lines[last + 1:])


def convert(root):
    if os.path.exists(os.path.join(root, "records")):
        die("records/ exists already: the conversion runs once")
    parsed = parse_all(root, lambda p: read_file(root, p))
    seen = {}
    counts = collections.Counter()
    for v, t, cols, recs in parsed:
        write(root, f"records/views/{v['name']}.head.md", t.head)
        if t.tail:
            write(root, f"records/views/{v['name']}.tail.md", t.tail)
        for line_no, _, f in recs:
            key = f["id"].lower()
            if key in seen:
                die(f"{v['path']}:{line_no}: {f['id']} is already a row at {seen[key]}")
            seen[key] = f"{v['path']}:{line_no}"
            write(root, record_path(v["kind"], f["id"]), record_text(v["kind"], f))
            counts[v["kind"]] += 1
    views, idx = toml_views(parsed, root)
    write(root, "records/views/saturation-register.head.md", idx.head)
    if idx.tail:
        write(root, "records/views/saturation-register.tail.md", idx.tail)
    text = "".join("[[view]]\n" + "".join(f"{k} = {value(x)}\n" for k, x in ent) + "\n" for ent in views)
    write(root, "records/views.toml", text.rstrip("\n") + "\n")
    print(f"records_import: {counts['decision']} decision, {counts['compat']} compat, {counts['saturation']} saturation records; {len(views)} views")
    for letter, e in ESCAPES:
        print(f"records_import: normalisation ({letter}): {e}")


# ---- the proof ----

def git_show(root, rev, path):
    r = subprocess.run(["git", "-C", root, "show", f"{rev}:{path}"], capture_output=True)
    if r.returncode != 0:
        die(f"git show {rev}:{path}: {r.stderr.decode().strip()}")
    return r.stdout.decode("utf-8")


def added_ids(root):
    """Records that carry a `story` (made after the conversion, not converted rows): {id}."""
    out = set()
    for d, _, files in os.walk(os.path.join(root, "records")):
        for f in files:
            if f.endswith(".toml") and f != "views.toml":
                text = read_file(root, os.path.relpath(os.path.join(d, f), root))
                if re.search(r"^story = ", text, re.M):
                    out.add(re.search(r'^id = "([^"]*)"', text, re.M).group(1))
    return out


def lis_keep(seq):
    """Indices of a longest strictly increasing subsequence of seq (the rows that did not move)."""
    import bisect
    tails, tails_i, prev = [], [], [-1] * len(seq)
    for i, x in enumerate(seq):
        j = bisect.bisect_left(tails, x)
        if j == len(tails):
            tails.append(x)
            tails_i.append(i)
        else:
            tails[j], tails_i[j] = x, i
        prev[i] = tails_i[j - 1] if j > 0 else -1
    keep, i = set(), tails_i[-1] if tails_i else -1
    while i >= 0:
        keep.add(i)
        i = prev[i]
    return keep


def verify(root, base):
    old = parse_all(root, lambda p: git_show(root, base, p))
    old_norms = list(ESCAPES)
    added = added_ids(root)
    bad, norm = [], collections.defaultdict(list)
    counts = collections.Counter()
    total_views = 0
    for v, t_old, cols, recs in old:
        total_views += 1
        new_text = read_file(root, v["path"])
        if not new_text.startswith(GENERATED + "\n"):
            bad.append(f"{v['path']}:1: not generated (first line is not the @generated mark)")
            continue
        norm["a"].append(f"{v['path']}:1: @generated line added")
        t_new = Table(v["path"], new_text[len(GENERATED) + 1:], v["row_prefix"])
        for what in ("head", "header", "separator", "tail"):
            if getattr(t_new, what) != getattr(t_old, what):
                bad.append(f"{v['path']}: {what} differs from {base}")
        if t_new.strays:
            bad.append(f"{v['path']}: generated view has lines inside its table that are not rows: {t_new.strays[:3]}")
        new_rows = [line for _, line in t_new.rows]
        series = default_series_order(list(dict.fromkeys(series_of(f["id"]) for _, _, f in recs)))
        new_ids = [t_new.cells(line, len(cols))[0] if v["kind"] != "saturation" else None for line in new_rows]
        extra = [line for line, rid in zip(new_rows, new_ids) if rid in added]
        kept = [line for line, rid in zip(new_rows, new_ids) if rid not in added]
        old_rows = [line for _, line, _ in recs]
        if collections.Counter(kept) != collections.Counter(old_rows):
            missing = collections.Counter(old_rows) - collections.Counter(kept)
            more = collections.Counter(kept) - collections.Counter(old_rows)
            bad.append(f"{v['path']}: rows differ: {sum(missing.values())} old rows missing, {sum(more.values())} rows not in {base} (first: {next(iter(missing or more))[:100]})")
            continue
        counts[v["kind"]] += len(old_rows)
        for rid in [r for r in new_ids if r in added]:
            norm["added"].append(f"{v['path']}: row {rid} added after the conversion (a record with a story)")
        if v["kind"] == "saturation":
            expect = old_rows  # SR ids follow today's file order
        else:
            keyed = sorted(recs, key=lambda r: id_key(r[2]["id"], series))
            expect = [line for _, line, _ in keyed]
            ids = [id_key(r[2]["id"], series) for r in recs]
            moved = [recs[i][0] for i in range(len(recs)) if i not in lis_keep(ids)]
            if moved:
                norm["b"].append(f"{v['path']}: {len(moved)} rows moved into id order (lines in {base}: {', '.join(map(str, moved))})")
        if kept != expect:
            bad.append(f"{v['path']}: row order is not the id order")
        for line_no, text in t_old.strays:
            norm["c"].append(f"{v['path']}:{line_no}: dropped line {text!r} inside the table")
        del extra
    # the index
    files = sat_files(root)
    oi = Index(git_show(root, base, SAT_INDEX), SAT_INDEX)
    new_text = read_file(root, SAT_INDEX)
    total_views += 1
    if not new_text.startswith(GENERATED + "\n"):
        bad.append(f"{SAT_INDEX}:1: not generated")
    else:
        norm["a"].append(f"{SAT_INDEX}:1: @generated line added")
        ni = Index(new_text[len(GENERATED) + 1:], SAT_INDEX)
        if ni.head != oi.head or ni.tail != oi.tail:
            bad.append(f"{SAT_INDEX}: head or tail differs from {base}")
        if ni.strays:
            bad.append(f"{SAT_INDEX}: stray lines in the generated list")
        if [e[1] for e in ni.entries] != sorted(files)[1:] or sorted(e[1] for e in oi.entries) != [e[1] for e in ni.entries]:
            bad.append(f"{SAT_INDEX}: sections listed differ")
        for line_no, text in oi.strays:
            norm["d"].append(f"{SAT_INDEX}:{line_no}: dropped stray line {text!r}")
        on = [e[1] for e in oi.entries]
        for i in sorted(set(range(len(on))) - lis_keep(on)):
            norm["d"].append(f"{SAT_INDEX}:{oi.entries[i][0]}: section {on[i]} moved into number order")
        old_by = {e[1]: e for e in oi.entries}
        for e in ni.entries:
            o = old_by.get(e[1])
            heading = next((line[3:] for line in read_file(root, f"{SAT_DIR}/{files[e[1]]}").split("\n") if line.startswith("## ")), None)
            if e[3] != heading:
                bad.append(f"{SAT_INDEX}: section {e[1]} title is not its file's heading")
            if o and o[3] != e[3]:
                norm["d"].append(f"{SAT_INDEX}:{o[0]}: section {e[1]} title taken from its heading ({o[3]!r} -> {e[3]!r})")
            if o and o[2] != e[2]:
                bad.append(f"{SAT_INDEX}: section {e[1]} links another file")
    print(f"verify: base {base}; {total_views} views; rows equal as multisets: {counts['decision']} decision, {counts['compat']} compat, {counts['saturation']} saturation")
    for letter, text in old_norms:
        norm[letter].append(text)
    labels = {"a": "(a) @generated first line", "b": "(b) rows reordered by id", "c": "(c) stray lines inside a table dropped", "d": "(d) saturation index", "e": "(e) bare `|` in a cell escaped", "f": "(f) empty cell spelled `|  |`", "g": "(g) control byte restored to `\\N`", "added": "records added after the conversion"}
    for k in ("a", "b", "c", "d", "e", "f", "g", "added"):
        print(f"verify: {labels[k]}: {len(norm[k])}")
        for n in norm[k]:
            print(f"verify:   {n}")
    for b in bad:
        print(f"verify: FAIL: {b}")
    if bad:
        sys.exit(1)
    print("verify: ok: heads, tails, headers and row multisets byte-identical; order = id order; nothing else differs")


# ---- rows a pre-cutover branch added ----

def from_diff(root, base, branch):
    views = {v["path"]: v for v in views_of(root)}
    diff = subprocess.run(["git", "-C", root, "diff", "--no-color", "-U0", f"{base}...{branch}", "--", DECISION_DIR, COMPAT_PATH, SAT_DIR], capture_output=True, text=True)
    if diff.returncode != 0:
        die(diff.stderr.strip())
    path, made = None, 0
    tables = {}
    for line in diff.stdout.split("\n"):
        if line.startswith("+++ "):
            path = line[6:] if line.startswith("+++ b/") else None
            continue
        if path not in views or not line.startswith("+| "):
            continue
        v = views[path]
        if path not in tables:
            tables[path] = Table(path, git_show(root, branch, path), v["row_prefix"])
        t = tables[path]
        row = line[1:]
        if row == t.header:
            continue
        cols = columns_for(v, t)
        f = dict(zip(cols, t.cells(row, len(cols))), status="active", body="")
        if v["kind"] == "decision":
            f["section"] = v["section"]
            rel = record_path("decision", f["id"])
        elif v["kind"] == "compat":
            if f["status"] not in COMPAT_STATUS:
                f["status_text"], f["status"] = f["status"], "registered"
            rel = record_path("compat", f["id"])
        else:
            f = dict(id="SR-NEW", section=v["section"], **f)
            k = 1
            while os.path.exists(os.path.join(root, f"records/pending/from-diff-{k}.toml")):
                k += 1
            rel = f"records/pending/from-diff-{k}.toml"
        if os.path.exists(os.path.join(root, rel)):
            print(f"from-diff: {rel} exists; row skipped")
            continue
        write(root, rel, record_text(v["kind"], f))
        print(f"from-diff: wrote {rel} (fill story and date by hand; check the record with `cargo xtask records check`)")
        made += 1
    print(f"from-diff: {made} record(s)")


def main(argv):
    root = os.getcwd()
    if not os.path.isfile(os.path.join(root, "xtask/Cargo.toml")):
        die("run from the tree root")
    if argv[:1] == ["--verify"]:
        base = argv[argv.index("--base") + 1] if "--base" in argv else "origin/next"
        verify(root, base)
    elif argv[:1] == ["--from-diff"] and len(argv) == 3:
        from_diff(root, argv[1], argv[2])
    elif not argv:
        convert(root)
    else:
        die("usage: records_import.py [--verify [--base REF] | --from-diff BASE BRANCH]")


if __name__ == "__main__":
    main(sys.argv[1:])
