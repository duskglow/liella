#!/bin/bash
# Trace the functions of the fault-bounded probe modes that no hot-text tier covers (D-X.62) into
# crates/libc-so/probe-text.keys. usage: tools/hottext/probe_text.sh <tree with built products> [--replace]
#   crates/core/tests/hot_text_products.rs bounds the page faults of `page_faults <mode>` for several
#   modes. The start-up read-only group (xtask/src/startup_ro.rs) takes the read-only data of the
#   functions those modes run: the hot-text tiers cover `true`, `locale` and the tool (HOT_TIERS there);
#   the modes in MODES below run functions the hot-text list files under `extra` (with every other
#   cold traced function), so they are traced here, each on its own, as the test runs them (env LANG,
#   linked as the test links page_faults.c). Output `<key>\textra\t<profiles>`, first-touch order,
#   the union over the profiles traced (merge.py: run once per profile, like regen.sh, which calls this).
#   A new fault-bounded mode whose functions sit in no HOT_TIERS tier goes into MODES.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
T=$(cd "$1" && pwd); shift
replace=0
if [ "${1:-}" = --replace ]; then replace=1; fi
MODES="localtime localtime_mktime"
profile=$(cat "$T/target/liella/.profile" 2>/dev/null || true)
case $profile in fast|release) ;; *) echo "probe_text: $T/target/liella/.profile: want fast or release, got '$profile'" >&2; exit 1;; esac
work=$(mktemp -d "${TMPDIR:-/tmp}/probetext.XXXXXX")
trap 'rm -rf "$work"' EXIT
cc -std=gnu17 -O1 -static -nostdlib -fno-builtin "$T/target/liella/liella-crt1.o" "$T/crates/core/tests/oracle/page_faults.c" \
    "$T/target/liella/libc.a" -lgcc -o "$work/page_faults"
echo x > "$work/in.txt"
tagged=
for m in $MODES; do
    env -i PATH="$PATH" LANG=en_US.UTF-8 HOT_TEXT_OUT="$work/names.$m" HOT_TEXT_STDIN="$work/in.txt" HOT_TEXT_FOLLOW_FORK= timeout 900 \
        gdb -nx -batch -x "$here/trace_gdb.py" --args "$work/page_faults" "$m" > "$work/gdb.$m.log" 2>&1 || { tail -5 "$work/gdb.$m.log"; exit 1; }
    tagged="$tagged extra=$work/names.$m"  # merge.py takes hot-text tiers only; these functions' tier is extra
done
# shellcheck disable=SC2086
python3 -B "$here/keys.py" --tagged $tagged > "$work/probe.keys"
pkeys=$here/../../crates/libc-so/probe-text.keys
if [ $replace = 1 ] || [ ! -f "$pkeys" ]; then : > "$work/probe.old"; else grep -v '^#' "$pkeys" > "$work/probe.old" || true; fi
{
    echo "# @generated by tools/hottext/probe_text.sh; do not edit by hand."
    echo "# D-X.62: the functions the fault-bounded \`page_faults <mode>\` probes of crates/core/tests/hot_text_products.rs run that"
    echo "# no hot-text tier covers (modes: $MODES): build-stable keys (tools/hottext/keys.py), first-touch order."
    echo "# <key> TAB extra TAB <profiles traced in>."
    python3 -B "$here/merge.py" "$work/probe.old" "$work/probe.keys" "$profile" "${HOTTEXT_HOST_CLASS:?set by regen.sh (D-X.61)}"
} > "$pkeys.tmp"
mv "$pkeys.tmp" "$pkeys"
echo "probe-text: $(wc -l < "$work/probe.keys") keys traced ($profile), $(grep -vc '^#' "$pkeys") in $pkeys"
