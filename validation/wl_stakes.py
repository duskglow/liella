#!/usr/bin/env python3
"""WL-STAKES: real-shape stakes of the mem*, str* and malloc family, Liella vs glibc.

  wl_stakes.py spec   <shapes.tsv> <out.c> [--top K] [--cover F]
  wl_stakes.py report <out.c> <percall.log> <stakes.md> [--title T]

spec: aggregates validation/wl_shapes.sh's shapes.tsv over all workloads, keeps per symbol the most frequent shapes
(until --cover of the symbol's calls, default 0.9, at most --top, default 6) and writes a wl_percall spec (one CASE
per shape, calls = observed calls, size/aux = the bucket's mean) plus <out.c>.json describing the cases.
Run it with: export S=...; WLP_TAIL=0 bash validation/wl_percall.sh --spec <out.c> <worktree|rev> > percall.log
report: joins the percall table with the json: per symbol, sum over its shapes of calls x (Liella - glibc)
instructions:u per call (= the stake at the REAL shapes), covered fraction, and the same scaled to all its calls.
Pair cases: malloc/calloc/strdup cases include the free of the result, realloc the malloc of the old block and the
free (labelled in the table); free itself has no case of its own (its cost is inside those pairs).
Clean room: only the programs' calls are observed (wl_shapes) and glibc is measured as a black box (wl_percall).
"""
import json
import re
import sys
from collections import defaultdict

CAP = 1 << 20  # largest size a case uses (buffers are static); bigger shapes are clamped and flagged

BODY = {
    'memcpy': 'for (long i = 0; i < n; i++) pc_sink += (long)P_memcpy(B, A, *vs);',
    'mempcpy': 'for (long i = 0; i < n; i++) pc_sink += (long)P_mempcpy(B, A, *vs);',
    'memmove': 'for (long i = 0; i < n; i++) pc_sink += (long)P_memmove(B, A, *vs);',
    'memset': 'for (long i = 0; i < n; i++) pc_sink += (long)P_memset(B, (int)i, *vs);',
    'memcmp': 'MEMSETUP for (long i = 0; i < n; i++) pc_sink += P_memcmp(A, B, *vs); CHK(P_memcmp(A, B, *vs))',
    'bcmp': 'MEMSETUP for (long i = 0; i < n; i++) pc_sink += P_bcmp(A, B, *vs); CHK(P_bcmp(A, B, *vs) != 0)',
    '__memcmpeq': 'MEMSETUP for (long i = 0; i < n; i++) pc_sink += P___memcmpeq(A, B, *vs); CHK(P___memcmpeq(A, B, *vs) != 0)',
    'strlen': 'FILL(A, s) for (long i = 0; i < n; i++) pc_sink += (long)P_strlen(A); CHK(P_strlen(A))',
    'strchr': 'FILL(A, s - 1) if (f && s) A[s - 1] = \'x\', A[s] = 0; '
              'for (long i = 0; i < n; i++) pc_sink += (long)P_strchr(A, \'x\'); CHK(P_strchr(A, \'x\') != NULL)',
    'strrchr': 'FILL(A, s - 1) if (f && s > 1) A[0] = \'x\'; '
               'for (long i = 0; i < n; i++) pc_sink += (long)P_strrchr(A, \'x\'); CHK(P_strrchr(A, \'x\') != NULL)',
    'memchr': 'FILL(A, s) if (f && a < s) A[a] = \'x\'; '
              'for (long i = 0; i < n; i++) pc_sink += (long)P_memchr(A, \'x\', *vs); CHK(P_memchr(A, \'x\', *vs) != NULL)',
    'strcmp': 'FILL(A, s) FILL(B, s) if (s) A[s - 1] = 0, B[s - 1] = f ? 0 : \'b\'; '
              'for (long i = 0; i < n; i++) pc_sink += P_strcmp(A, B); CHK(P_strcmp(A, B))',
    'strncmp': 'FILL(A, s + 1) FILL(B, s + 1) if (a < s) { if (f) A[a] = B[a] = 0; else B[a] = \'b\'; } '
               'for (long i = 0; i < n; i++) pc_sink += P_strncmp(A, B, *vs); CHK(P_strncmp(A, B, *vs))',
    'strcpy': 'FILL(A, s) for (long i = 0; i < n; i++) pc_sink += (long)P_strcpy(B, A); CHKN(strlen(P_strcpy(B, A)))',
    'stpcpy': 'FILL(A, s) for (long i = 0; i < n; i++) pc_sink += (long)P_stpcpy(B, A); CHKN(P_stpcpy(B, A) - B)',
    'strncpy': 'FILL(A, a) for (long i = 0; i < n; i++) pc_sink += (long)P_strncpy(B, A, *vs); CHKN(strnlen(P_strncpy(B, A, *vs), *vs))',
    'strdup': 'FILL(A, s) for (long i = 0; i < n; i++) { char *p = P_strdup(A); pc_sink += p[0]; P_free(p); } '
               'CHKN(({ char *q = P_strdup(A); long r = (long)strlen(q); P_free(q); r; }))',
    'malloc': 'for (long i = 0; i < n; i++) { void *volatile p = P_malloc(*vs); P_free(p); }',
    'calloc': 'size_t m = a ? a : 1; for (long i = 0; i < n; i++) { void *volatile p = P_calloc(m, *vs / m); P_free(p); }',
    'realloc': 'for (long i = 0; i < n; i++) { void *p = a ? P_malloc(a) : NULL; void *volatile q = P_realloc(p, *vs); '
               'if (q) P_free(q); else P_free(p); }',
}
FPTRS = ('memcpy', 'mempcpy', 'memmove', 'memset', 'memcmp', 'bcmp', '__memcmpeq', 'strlen', 'strchr', 'strrchr',
         'memchr', 'strcmp', 'strncmp', 'strcpy', 'stpcpy', 'strncpy', 'strdup', 'malloc', 'calloc', 'realloc', 'free')
PAIR = {'strdup': '+free', 'malloc': '+free', 'calloc': '+free', 'realloc': 'malloc(old)+realloc+free'}
HEAD = '''/* Generated by validation/wl_stakes.py spec from wl_shapes.sh output: one case per real call shape. */
#include "percall.h"
#include <stddef.h>
int __memcmpeq(const void *, const void *, size_t);
static char A[%d + 64], B[%d + 64];
#define FILL(p, k) { size_t k_ = (size_t)(k); for (size_t j_ = 0; j_ < k_; j_++) (p)[j_] = 'a'; (p)[k_] = 0; }
#define MEMSETUP FILL(A, s) FILL(B, s) if (!f && a < s) B[a] = 'b';
#define CHK(e) PC_CHECKING { pc_check("%%ld", (long)PC_SIGN(e)); }
#define CHKN(e) PC_CHECKING { pc_check("%%ld", (long)(e)); }
/* Every measured call goes through a volatile function pointer: gcc cannot fold, hoist out of the loop or
 * inline-expand a call it cannot see (a direct strlen(A) / strcpy(B, A) was hoisted: 6 and 9 instr per call). */
''' % (CAP, CAP) + ''.join('static __typeof__(%s) *volatile P_%s = %s;\n' % (s, s, s) for s in FPTRS)


def load_shapes(path):
    agg = defaultdict(lambda: [0, 0, 0])
    for line in open(path, encoding='utf-8'):
        f = line.rstrip('\n').split('\t')
        if len(f) < 8 or f[1].startswith('#'):
            continue
        k = (f[1], int(f[2]), int(f[3]), int(f[4]))
        v = agg[k]
        v[0] += int(f[5]); v[1] += int(f[6]); v[2] += int(f[7])
    return agg


def spec(args):
    shapes, out = args[0], args[1]
    top = int(args[args.index('--top') + 1]) if '--top' in args else 6
    cover = float(args[args.index('--cover') + 1]) if '--cover' in args else 0.9
    agg = load_shapes(shapes)
    bysym = defaultdict(list)
    for (sym, slo, alo, fl), (c, ss, sa) in agg.items():
        bysym[sym].append((c, slo, alo, fl, ss, sa))
    cases, src = [], [HEAD]
    for sym in sorted(bysym):
        rows = sorted(bysym[sym], reverse=True)
        total = sum(r[0] for r in rows)
        if sym not in BODY:
            cases.append({'sym': sym, 'case': None, 'total': total})
            continue
        got = 0
        for i, (c, slo, alo, fl, ss, sa) in enumerate(rows[:top]):
            s, a = round(ss / c), round(sa / c)
            clamp = s > CAP
            s, a = min(s, CAP), min(a, CAP)
            if sym == 'memchr' and fl and a < s:  # found: the scan stops at the match - keep one vector of slack
                clamp = clamp or s > a + 64        # past it so the size bound is not the deciding branch
                s = min(s, a + 64)
            name = re.sub(r'\W', '', sym).lstrip('_') + '_%d' % i
            src.append('CASE(%s, %d, 1) { size_t s = %d, a = %d; int f = %d; (void)a; (void)f; '
                       'static volatile size_t vsz; vsz = s; volatile size_t *vs = &vsz; %s }\n'
                       % (name, c, s, a, fl, BODY[sym]))
            cases.append({'sym': sym, 'case': name, 'calls': c, 'size': s, 'aux': a, 'flag': fl, 'bucket': slo,
                          'clamped': clamp, 'total': total})
            got += c
            if got >= cover * total:
                break
    open(out, 'w', encoding='utf-8', newline='\n').write(''.join(src))
    json.dump(cases, open(out + '.json', 'w', encoding='utf-8', newline='\n'), indent=0)
    print('wl_stakes: %d cases for %d symbols -> %s' % (sum(1 for c in cases if c['case']), len(bysym), out))


def report(args):
    specf, logf, md = args[0], args[1], args[2]
    cases = json.load(open(specf + '.json', encoding='utf-8'))
    per = {}
    for line in open(logf, encoding='utf-8', errors='replace'):
        f = line.split()
        if len(f) >= 5 and re.fullmatch(r'[-\d.]+', f[1] or '') and re.fullmatch(r'[-\d.]+', f[3] or ''):
            per[f[0]] = (float(f[1]), float(f[3]), f[-1])  # glibc, new (no --base: column 3 is "-"), check
    syms = defaultdict(lambda: {'total': 0, 'cov': 0, 'gap': 0.0, 'g': 0.0, 'shapes': [], 'missing': 0})
    for c in cases:
        s = syms[c['sym']]
        s['total'] = c['total']
        if not c['case']:
            continue
        r = per.get(c['case'])
        if r is None:
            s['missing'] += 1
            continue
        g, l, chk = r
        s['cov'] += c['calls']; s['gap'] += c['calls'] * (l - g); s['g'] += c['calls'] * g
        s['shapes'].append('%s n=%d%s%s: %.0f/%.0f%s' % (
            c['case'], c['size'], ' a=%d' % c['aux'] if c['aux'] else '', ' eq/found' if c['flag'] else '',
            l, g, ' MISMATCH' if chk == 'MISMATCH' else ''))
    miss = sum(s['missing'] for s in syms.values())
    if miss:
        print('wl_stakes: WARNING %d cases missing from %s (a tail of the log? run wl_percall with WLP_TAIL=0)'
              % (miss, logf), file=sys.stderr)
    rows = []
    for sym, s in syms.items():
        scaled = s['gap'] * s['total'] / s['cov'] if s['cov'] else 0.0
        rows.append((scaled, sym, s))
    rows.sort(key=lambda r: -r[0])
    o = ['# WL-STAKES: real-shape stakes per symbol (30 wl_count workloads, glibc kit)', '',
         'stake = sum over the symbol\'s top shapes of calls x (Liella - glibc) instructions:u per call (wl_percall, '
         'deterministic); "scaled" extrapolates to all calls of the symbol by the covered fraction. Negative = Liella '
         'already below glibc. Pair cases: ' + ', '.join('%s %s' % kv for kv in PAIR.items()) + '.', '',
         '| # | symbol | calls | covered | stake (M instr) | scaled (M) | Liella/glibc | shapes (case n= a= : liella/glibc per call) |',
         '|---|---|---|---|---|---|---|---|']
    for i, (scaled, sym, s) in enumerate(rows, 1):
        ratio = (s['g'] + s['gap']) / s['g'] if s['g'] else 0
        o.append('| %d | %s%s | %d | %.0f%% | %.1f | %.1f | %.2f | %s |' % (
            i, sym, ' (' + PAIR[sym] + ')' if sym in PAIR else '', s['total'],
            100.0 * s['cov'] / s['total'] if s['total'] else 0, s['gap'] / 1e6, scaled / 1e6, ratio,
            '; '.join(s['shapes']) or ('no case' if not s['missing'] else '%d cases missing from the log' % s['missing'])))
    below = [r[1] for r in rows if r[0] < 0]
    o += ['', 'Already below glibc at the real shapes: ' + (', '.join(below) or 'none'), '']
    open(md, 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
    print('wl_stakes: %d symbols -> %s' % (len(rows), md))


if __name__ == '__main__':
    if len(sys.argv) < 4 or sys.argv[1] not in ('spec', 'report'):
        print(__doc__)
        sys.exit(2)
    (spec if sys.argv[1] == 'spec' else report)(sys.argv[2:])
