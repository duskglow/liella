//! `cargo xtask bench --stage <out.tar>` and `./xtask-bin bench --no-build --staged` (XTASK-BENCH-STAGE).
//!
//! Timing hosts have no compiler, so a timing run measures a tree built elsewhere. `--stage` writes that tree as
//! one tarball: the workspace `Cargo.toml` and `xtask/Cargo.toml` (so the root is found from the unpacked
//! directory), `bench/` (the tables the run reads), `target/liella` (the products and bench programs; not the
//! generated stress files), the Rust bench examples it selected, the running xtask binary as `xtask-bin`, and
//! `bench-stage.manifest`: the commit, a hash of the source tree, the build profile and the sha256 of every
//! staged product. tar keeps the build's mtimes.
//!
//! A `--no-build` run in a tree holding the manifest (or `--staged`, which requires it) checks each product's
//! sha256 against the manifest instead of comparing mtimes (unpacking, clock skew or a `touch` can make a correct
//! product look older than its sources), never asks git or the build host's path, and prints the manifest's
//! commit in its header. A product that does not match is refused.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

/// The manifest's name, at the root of the staged tree.
pub(crate) const MANIFEST: &str = "bench-stage.manifest";
/// The xtask binary's name in the staged tree.
const XTASK_BIN: &str = "xtask-bin";
/// Generated by `bench --stress` on the measuring host, never staged.
const STRESS_DIR: &str = "target/liella/bench/stress";

pub(crate) struct Manifest {
    pub commit: String,
    pub tree: String,
    pub profile: String,
    pub built_on: String,
    /// (sha256, path relative to the staged root), sorted by path.
    pub products: Vec<(String, String)>,
}

impl Manifest {
    fn text(&self) -> String {
        let mut s = format!(
            "# @generated by cargo xtask bench --stage (XTASK-BENCH-STAGE); `--no-build` checks the products against it\ncommit\t{}\ntree\t{}\nprofile\t{}\nbuilt_on\t{}\n",
            self.commit, self.tree, self.profile, self.built_on
        );
        for (h, p) in &self.products {
            s.push_str(&format!("product\t{h}\t{p}\n"));
        }
        s
    }

    fn parse(text: &str) -> Result<Manifest, String> {
        let mut m = Manifest { commit: String::new(), tree: String::new(), profile: String::new(), built_on: String::new(), products: Vec::new() };
        for l in text.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
            let f: Vec<&str> = l.split('\t').collect();
            match f.as_slice() {
                ["commit", v] => m.commit = v.to_string(),
                ["tree", v] => m.tree = v.to_string(),
                ["profile", v] => m.profile = v.to_string(),
                ["built_on", v] => m.built_on = v.to_string(),
                ["product", h, p] if h.len() == 64 && !p.is_empty() && !p.split('/').any(|c| c == "..") => m.products.push((h.to_string(), p.to_string())),
                _ => return Err(format!("{MANIFEST}: bad line `{l}`")),
            }
        }
        if m.commit.is_empty() || m.products.is_empty() {
            return Err(format!("{MANIFEST}: no commit or no products"));
        }
        Ok(m)
    }
}

/// The sha256 of each file (paths relative to `root`), in order, from `sha256sum` (coreutils, on every host).
fn sha256_files(root: &Path, rel: &[String]) -> Result<Vec<String>, String> {
    let mut out = Vec::with_capacity(rel.len());
    for chunk in rel.chunks(512) {
        if let Some(p) = chunk.iter().find(|p| !root.join(p).is_file()) {
            return Err(format!("{}: missing", root.join(p).display()));
        }
        let o = Command::new("sha256sum").arg("--").args(chunk).current_dir(root).output().map_err(|e| format!("sha256sum: {e}"))?;
        if !o.status.success() {
            return Err(format!("sha256sum failed: {}", String::from_utf8_lossy(&o.stderr)));
        }
        let text = String::from_utf8_lossy(&o.stdout);
        let hashes: Vec<String> = text.lines().filter_map(|l| l.get(..64).map(str::to_string)).collect();
        if hashes.len() != chunk.len() {
            return Err(format!("sha256sum: {} hashes for {} files", hashes.len(), chunk.len()));
        }
        out.extend(hashes);
    }
    Ok(out)
}

fn sha256_text(text: &str) -> Result<String, String> {
    use std::io::Write;
    let mut c = Command::new("sha256sum").stdin(Stdio::piped()).stdout(Stdio::piped()).spawn().map_err(|e| format!("sha256sum: {e}"))?;
    c.stdin.take().ok_or("sha256sum: no stdin")?.write_all(text.as_bytes()).map_err(|e| format!("sha256sum: {e}"))?;
    let o = c.wait_with_output().map_err(|e| format!("sha256sum: {e}"))?;
    String::from_utf8_lossy(&o.stdout).get(..64).map(str::to_string).ok_or_else(|| "sha256sum: no output".into())
}

/// The files below `root/dir` (relative to `root`, sorted), skipping `target`, `.git` and `skip` (relative to `root`).
fn files_below(root: &Path, dir: &str, skip: Option<&str>) -> Vec<String> {
    let mut v = Vec::new();
    let mut stack = vec![root.join(dir)];
    while let Some(d) = stack.pop() {
        let Ok(rd) = fs::read_dir(&d) else { continue };
        for e in rd.flatten() {
            let p = e.path();
            let Some(rel) = p.strip_prefix(root).ok().and_then(Path::to_str).map(str::to_string) else { continue };
            if skip == Some(rel.as_str()) || p.file_name().is_some_and(|n| n == "target" || n == ".git") {
                continue;
            }
            if p.is_dir() {
                stack.push(p);
            } else if p.is_file() {
                v.push(rel);
            }
        }
    }
    v.sort();
    v
}

/// The commit the products were built from: git when the tree has it, else the `head=` line of the `.synced`
/// file a role directory carries (it has no .git), else `unknown`. `+dirty` marks uncommitted changes.
fn commit_of(root: &Path) -> String {
    let git = |args: &[&str]| Command::new("git").arg("-C").arg(root).args(args).stderr(Stdio::null()).output().ok().filter(|o| o.status.success());
    if let Some(o) = git(&["rev-parse", "HEAD"]) {
        let head = String::from_utf8_lossy(&o.stdout).trim().to_string();
        let dirty = git(&["status", "--porcelain", "--untracked-files=no"]).is_some_and(|o| !o.stdout.is_empty());
        return if dirty { format!("{head}+dirty") } else { head };
    }
    let synced = fs::read_to_string(root.join(".synced")).unwrap_or_default();
    let val = |k: &str| synced.lines().find_map(|l| l.strip_prefix(k).map(|v| v.trim().to_string())).filter(|v| !v.is_empty());
    match (val("head="), val("dirty=")) {
        (Some(h), Some(d)) if d != "clean" => format!("{h}+dirty({d})"),
        (Some(h), _) => h,
        _ => "unknown".into(),
    }
}

/// Writes the staged tree of `root` to `out`: see the module comment. `rust_benches` are the Rust examples the
/// selection measures (`target/release/examples/<name>`), `xtask_exe` the binary staged as `xtask-bin`.
pub(crate) fn write_stage(root: &Path, out: &Path, rust_benches: &[&str], xtask_exe: &Path) -> Result<Manifest, String> {
    let mut products = files_below(root, "target/liella", Some(STRESS_DIR));
    for b in rust_benches {
        products.push(format!("target/release/examples/{b}"));
    }
    products.sort();
    let hashes = sha256_files(root, &products)?;
    // The source tree's identity, also without git: sha256 over the `<sha256>  <path>` lines of every file of the
    // inputs (crates/, csys/, include/, bench/, Cargo.toml, Cargo.lock).
    let mut srcs: Vec<String> = ["crates", "csys", "include", "bench"].iter().flat_map(|d| files_below(root, d, None)).collect();
    srcs.extend(["Cargo.toml", "Cargo.lock"].iter().filter(|f| root.join(f).is_file()).map(|f| f.to_string()));
    let src_hashes = sha256_files(root, &srcs)?;
    let listing: String = src_hashes.iter().zip(&srcs).map(|(h, p)| format!("{h}  {p}\n")).collect();
    let tree = sha256_text(&listing)?;
    let profile = fs::read_to_string(root.join("target/liella/.profile")).map(|s| s.trim().to_string()).unwrap_or_else(|_| "unknown".into());
    let built_on = Command::new("hostname").output().ok().map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string()).filter(|s| !s.is_empty()).unwrap_or_else(|| "?".into());

    let name = out.file_name().and_then(|n| n.to_str()).ok_or_else(|| format!("--stage: `{}` is not a file name", out.display()))?;
    let parts = out.with_file_name(format!(".{name}.parts"));
    let _ = fs::remove_dir_all(&parts);
    fs::create_dir_all(&parts).map_err(|e| format!("{}: {e}", parts.display()))?;
    fs::copy(xtask_exe, parts.join(XTASK_BIN)).map_err(|e| format!("{} -> {XTASK_BIN}: {e}", xtask_exe.display()))?;
    let bin_hash = sha256_files(&parts, &[XTASK_BIN.to_string()])?.remove(0);
    let mut listed: Vec<(String, String)> = hashes.into_iter().zip(products.iter().cloned()).collect();
    listed.push((bin_hash, XTASK_BIN.to_string()));
    listed.sort_by(|a, b| a.1.cmp(&b.1));
    let m = Manifest { commit: commit_of(root), tree, profile, built_on, products: listed };
    fs::write(parts.join(MANIFEST), m.text()).map_err(|e| format!("{MANIFEST}: {e}"))?;

    let mut tar = Command::new("tar");
    tar.arg("-cf").arg(out).arg(format!("--exclude={STRESS_DIR}")).arg("-C").arg(root);
    tar.args(["Cargo.toml", "xtask/Cargo.toml", "bench"]).args(&products);
    tar.arg("-C").arg(&parts).args([MANIFEST, XTASK_BIN]);
    let st = tar.output().map_err(|e| format!("tar: {e}"));
    let _ = fs::remove_dir_all(&parts);
    let st = st?;
    if !st.status.success() {
        return Err(format!("tar -cf {} failed: {}", out.display(), String::from_utf8_lossy(&st.stderr)));
    }
    Ok(m)
}

/// A `--no-build` run's view of the staging: `None` when `root` holds no manifest (the mtime checks apply);
/// otherwise the manifest, after every listed product was found with its listed sha256 (an error otherwise).
pub(crate) fn load_verified(root: &Path) -> Result<Option<Manifest>, String> {
    let path = root.join(MANIFEST);
    let Ok(text) = fs::read_to_string(&path) else { return Ok(None) };
    let m = Manifest::parse(&text)?;
    let rel: Vec<String> = m.products.iter().map(|(_, p)| p.clone()).collect();
    let got = sha256_files(root, &rel).map_err(|e| format!("bench --staged: {e} (listed in {MANIFEST}); stage the tree again"))?;
    for ((want, p), got) in m.products.iter().zip(&got) {
        if want != got {
            return Err(format!("bench --staged: {p} does not match {MANIFEST} (sha256 {got}, manifest {want}): the staged tree changed after `bench --stage`; stage it again"));
        }
    }
    Ok(Some(m))
}

/// The header line naming what a staged run measures.
pub(crate) fn header(m: &Manifest) -> String {
    format!(
        "staged: commit {}, tree {}, profile {}, built on {}; {} products match {MANIFEST} (sha256; mtimes not used)",
        m.commit,
        m.tree.get(..16).unwrap_or(&m.tree),
        m.profile,
        m.built_on,
        m.products.len()
    )
}

/// The path `--stage` was given, made absolute (the build runs with other working directories).
pub(crate) fn out_path(arg: &str) -> PathBuf {
    let p = PathBuf::from(arg);
    if p.is_absolute() { p } else { std::env::current_dir().map(|d| d.join(&p)).unwrap_or(p) }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;

    fn write(p: &Path, text: &str) {
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, text).unwrap();
    }

    fn set_newer(p: &Path) {
        let later = std::time::SystemTime::now() + std::time::Duration::from_secs(3600);
        fs::File::options().write(true).open(p).unwrap().set_modified(later).unwrap();
    }

    fn args(a: &[&str]) -> Vec<String> {
        a.iter().map(|s| s.to_string()).collect()
    }

    // XTASK-BENCH-STAGE: no spec clause (developer tooling). A staged tree, unpacked elsewhere with its sources
    // made newer than its products, runs a `--no-build` row (the mtime checks refuse it without the manifest);
    // a product changed after staging is refused by its hash; `--staged` without a manifest is refused.
    #[test]
    fn staged_tree_runs_without_mtimes_and_refuses_a_changed_product() {
        let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("../target/xtask-stage-test");
        let _ = fs::remove_dir_all(&base);
        let (src, dst) = (base.join("src"), base.join("unpacked"));
        write(&src.join("Cargo.toml"), "[workspace]\n");
        write(&src.join("xtask/Cargo.toml"), "[package]\n");
        write(&src.join("crates/a/src/lib.rs"), "// source\n");
        write(&src.join("csys/src/b.c"), "/* source */\n");
        write(&src.join("bench/budgets.tsv"), "cbench_stagetest\trow\tmax_ns\t1000000\tstage test\n");
        write(&src.join("bench/host_limits.tsv"), "# none\n");
        write(&src.join("bench/instr_limits.tsv"), "# none\n");
        write(&src.join("bench/c/cbench_stagetest.c"), "/* the bench source */\n");
        write(&src.join("target/liella/libc.a"), "!<arch>\n");
        write(&src.join("target/liella/.profile"), "release\n");
        write(&src.join("target/liella/bench/stress/big"), "generated, never staged\n");
        let exe = src.join("target/liella/bench/cbench_stagetest");
        write(&exe, "#!/bin/sh\nprintf 'row\\t5\\n'\n");
        fs::set_permissions(&exe, fs::Permissions::from_mode(0o755)).unwrap();
        let tar = base.join("stage.tar");
        let m = write_stage(&src, &tar, &[], &std::env::current_exe().unwrap()).unwrap();
        assert_eq!(m.profile, "release");
        assert!(m.products.iter().any(|(_, p)| p == "target/liella/bench/cbench_stagetest") && m.products.iter().any(|(_, p)| p == XTASK_BIN), "{:?}", m.products);
        assert!(!m.products.iter().any(|(_, p)| p.starts_with(STRESS_DIR)), "{:?}", m.products);

        fs::create_dir_all(&dst).unwrap();
        let st = Command::new("tar").arg("-xf").arg(&tar).arg("-C").arg(&dst).status().unwrap();
        assert!(st.success());
        assert!(dst.join(MANIFEST).is_file() && dst.join(XTASK_BIN).is_file() && !dst.join(STRESS_DIR).exists());
        for p in ["bench/c/cbench_stagetest.c", "bench/budgets.tsv", "Cargo.toml"] {
            set_newer(&dst.join(p));
        }
        let run = |extra: &[&str]| crate::bench::run(&dst, &args(&[&["--no-build", "--only", "cbench_stagetest", "--runs", "1"], extra].concat()));

        // without the manifest the disturbed mtimes are refused (the failure this staging removes)
        fs::rename(dst.join(MANIFEST), base.join("aside")).unwrap();
        let e = run(&[]).unwrap_err();
        assert!(e.contains("--no-build"), "{e}");
        let e = run(&["--staged"]).unwrap_err();
        assert!(e.contains(MANIFEST), "{e}");
        fs::rename(base.join("aside"), dst.join(MANIFEST)).unwrap();

        // with it the row runs, detected or named
        run(&[]).unwrap();
        run(&["--staged"]).unwrap();

        // a product changed after staging (still a working program) is refused
        let staged_exe = dst.join("target/liella/bench/cbench_stagetest");
        let mut text = fs::read_to_string(&staged_exe).unwrap();
        text.push_str("# changed after staging\n");
        fs::write(&staged_exe, text).unwrap();
        let e = run(&["--staged"]).unwrap_err();
        assert!(e.contains("target/liella/bench/cbench_stagetest does not match"), "{e}");
        let _ = fs::remove_dir_all(&base);
    }

    // XTASK-BENCH-STAGE: no spec clause (developer tooling). The manifest reads back what it wrote and refuses
    // malformed lines and paths that leave the tree.
    #[test]
    fn manifest_round_trips_and_rejects_bad_lines() {
        let h = "a".repeat(64);
        let m = Manifest { commit: "c0ffee".into(), tree: h.clone(), profile: "release".into(), built_on: "shiki".into(), products: vec![(h.clone(), "target/liella/libc.a".into())] };
        let back = Manifest::parse(&m.text()).unwrap();
        assert_eq!((back.commit.as_str(), back.profile.as_str(), back.products.len()), ("c0ffee", "release", 1));
        assert!(Manifest::parse(&format!("commit\tc\nproduct\t{h}\t../x\n")).is_err());
        assert!(Manifest::parse("commit\tc\nproduct\tshort\tx\n").is_err());
        assert!(Manifest::parse("commit\tc\n").is_err());
    }
}
