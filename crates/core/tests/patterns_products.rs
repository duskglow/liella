//! Patterns end to end (spec §14.7–14.10; D-14.4, D-14.5): `tests/oracle/patterns_diff.c` built
//! against the host C library and statically against Liella's products, each run by
//! `tests/oracle/patterns_run.sh` (the fixture and the `C.UTF-8` and `en_US.UTF-8` locales in a
//! scratch directory); the outputs are compared section by section. Liella runs twice, with the
//! name-service cache on and off (`nscache_mode.sh`, D-16.10; `~user` looks up passwd), when
//! passwordless `sudo` is available, and once as it is otherwise.
//!
//! * **Regular expressions** (`regex`, `regex corpus`, `GNU regex interface`, §14.9): every line
//!   must equal the reference's, except
//!   * the lines the owner's submatch ruling changes (D-14.4: POSIX XBD 9.1 in every case,
//!     categories I1–I4, E2 and O1 of `spec/behaviour/regex-submatch-analysis.md`): for those,
//!     `spec/behaviour/regex-posix.expected.txt` (generated by
//!     `spec/tools/regex_posix_reference.py` from the record, an independent reading of XBD 9.1)
//!     gives the line POSIX requires, and Liella must print exactly that line;
//!   * the decided differences in [`KNOWN_REGEX`].
//!
//!   The reference's regex sections must also equal the record (`patterns.glibc.txt.gz`), which
//!   keeps the expectation file in step with the oracle.
//! * **`fnmatch`, `glob`, `wordexp`** (§14.7, §14.8, §14.10): every line must equal the
//!   reference's, except the decided differences in [`KNOWN`] (each with its reason: a ruling,
//!   the spec or the documentation), and the `fnmatch` corpus lines (`fc`) where glibc treats a
//!   period after the characters a `*` matched as leading: there Liella must equal an
//!   independent reading of fnmatch(3)'s definition ([`reference_fc`]). The reference's `fnmatch`
//!   and `wordexp` sections must equal the record; its `glob` section too, except the lines in
//!   directory order (`GLOB_NOSORT`), which name the file system (the `fs:` line; ext4 in the
//!   record) and are compared with the record as sets, and the aborted walk of `tree/*/*`,
//!   whose `magchar` flag depends on the same order ([`order_dependent_magchar`]).
//! * The `glob compat` section is not produced: the products cannot bind `glob@GLIBC_2.2.5`
//!   (phase 15, its ledger).
//!
//! Needs the products (`cargo xtask so`), a C compiler and `localedef`; without the latter two
//! the test says so and passes.
