// ------------------------------------------------------------------------------ §23.4 timers

export! { "GLIBC_2.2.5";
pub extern "C" fn alarm(seconds: c_uint) -> c_uint {
    // It cannot fail (§23.4): the kernel's call always succeeds.
    CSys.alarm(seconds).unwrap_or(0)
}}

export! { "GLIBC_2.2.5";
pub extern "C" fn ualarm(value: c_uint, interval: c_uint) -> c_uint {
    clock_compat::ualarm(&CSys, value, interval).unwrap_or_else(|e| ret::value_with(c_uint::MAX, Some(e)))
}}

export! { "GLIBC_2.2.5";
pub extern "C" fn setitimer(which: c_int, new: Option<&Itimerval>, old: Option<&mut Itimerval>) -> c_int {
    // A NULL setting is EFAULT (S6; the kernel would take it as zero, which it deprecates).
    ret::store_if(old, conv::req(new).and_then(|n| CSys.setitimer(conv::bits(which), n)))
}}

export! { "GLIBC_2.2.5";
pub extern "C" fn getitimer(which: c_int, cur: Option<&mut Itimerval>) -> c_int {
    ret::store(cur, CSys.getitimer(conv::bits(which)))
}}

export! { "GLIBC_2.34";
pub extern "C" fn timer_create(clock: c_int, event: Option<&SigEvent>, id: Option<&mut *mut c_void>) -> c_int {
    // UNSAFE(slice) SAFETY: a SIGEV_THREAD event's sigev_notify_attributes is NULL or an initialised pthread_attr_t (§22.2).
    ret::zero(conv::req(id).and_then(|id| timer::create(clock, event, unsafe { conv::opt_obj64(timer::attributes(event)) }).map(|t| *id = ret::addr(t))))
}}

