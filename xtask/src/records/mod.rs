//! Records (RECORDS-1, D-X.55): decision rows, compat flags and the classified saturation rows are one file per record
//! under `records/`, in a strict TOML subset (`toml.rs`); the markdown tables are generated views
//! (`records/views.toml`, `render.rs`) that the train regenerates and branches never edit.
//!
//! | Command | Does |
//! |---|---|
//! | `records-gen [--check] [--in-place]` | render every view under `target/records-views/<view path>` (D-X.59: the tracked
//! views are train-owned, so a branch reads them there and has nothing to restore); in place only on the train
//! (`LIELLA_TRAIN=1`) or with `--in-place`; `--check` names each stale tracked view (`<file> is stale: run ...`) |
//! | `records check` | the validation (`check.rs`); also the static check `records` |
//! | `records fmt [--check]` | rewrite records in canonical form (keys in schema order) |
//! | `records new <kind> <id> [--section S] [--series S] [--story S]` | write a canonical skeleton |
//!
//! Records are loaded with `read_dir` and sorted before use: nothing depends on directory order.

mod check;
mod render;
mod schema;
mod toml;

use std::path::{Path, PathBuf};

pub use schema::Kind;
use toml::Value;

pub const DIR: &str = "records";
pub const VIEWS: &str = "records/views.toml";
/// Where a branch's run of a train-owned generator writes (D-X.59): `<root>/target/records-views/<tracked path>`.
pub const OUT_OF_TREE: &str = "target/records-views";
pub const GENERATED: &str = "<!-- @generated by `cargo xtask records-gen` from records/; edit the records, never this file -->";

/// One record file.
#[derive(Clone, Debug)]
pub struct Record {
    pub kind: Kind,
    /// Path relative to the root, `/`-separated.
    pub path: String,
    /// Under `records/pending/` (a placeholder id).
    pub pending: bool,
    pub entries: Vec<toml::Entry>,
}

impl Record {
    pub fn get(&self, key: &str) -> Option<&Value> {
        self.entries.iter().find(|e| e.key == key).map(|e| &e.value)
    }
    pub fn str(&self, key: &str) -> Option<&str> {
        match self.get(key) {
            Some(Value::Str(s) | Value::Body(s)) => Some(s),
            _ => None,
        }
    }
    pub fn list(&self, key: &str) -> &[String] {
        match self.get(key) {
            Some(Value::List(l)) => l,
            _ => &[],
        }
    }
    pub fn id(&self) -> &str {
        self.str("id").unwrap_or("")
    }
    pub fn line(&self, key: &str) -> usize {
        self.entries.iter().find(|e| e.key == key).map_or(1, |e| e.line)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ViewKind {
    Table(Kind),
    /// `docs/saturation-register.md`: one line per section file, from its `## <n>. <title>` heading.
    Index,
}

/// One view of `records/views.toml`.
#[derive(Clone, Debug)]
pub struct View {
    pub name: String,
    pub path: String,
    pub kind: ViewKind,
    pub section: Option<String>,
    pub series: Vec<String>,
    pub header: String,
    pub separator: String,
    pub columns: Vec<String>,
    pub dir: Option<String>,
    pub head: String,
    pub tail: Option<String>,
}

const VIEW_KEYS: [&str; 11] = ["name", "path", "kind", "section", "series", "header", "separator", "columns", "dir", "head", "tail"];

pub fn load_views(root: &Path) -> Result<Vec<View>, String> {
    let text = std::fs::read_to_string(root.join(VIEWS)).map_err(|e| format!("{VIEWS}: {e}"))?;
    let tables = toml::parse_tables(&text).map_err(|(l, m)| format!("{VIEWS}:{l}: {m}"))?;
    let mut views = Vec::new();
    for t in tables {
        let at = t.first().map_or(0, |e| e.line);
        let mut pos = 0;
        for e in &t {
            match VIEW_KEYS.iter().skip(pos).position(|k| *k == e.key) {
                Some(p) => pos += p + 1,
                None => return Err(format!("{VIEWS}:{}: key `{}` unknown or out of order ({})", e.line, e.key, VIEW_KEYS.join(" "))),
            }
        }
        let s = |k: &str| t.iter().find(|e| e.key == k).and_then(|e| if let Value::Str(s) = &e.value { Some(s.clone()) } else { None });
        let l = |k: &str| t.iter().find(|e| e.key == k).and_then(|e| if let Value::List(l) = &e.value { Some(l.clone()) } else { None }).unwrap_or_default();
        let need = |k: &str| s(k).ok_or_else(|| format!("{VIEWS}:{at}: view without `{k}`"));
        let kind = match need("kind")?.as_str() {
            "index" => ViewKind::Index,
            k => ViewKind::Table(Kind::from_name(k).ok_or_else(|| format!("{VIEWS}:{at}: unknown kind {k:?}"))?),
        };
        let table = matches!(kind, ViewKind::Table(_));
        views.push(View {
            name: need("name")?,
            path: need("path")?,
            kind,
            section: s("section"),
            series: l("series"),
            header: if table { need("header")? } else { String::new() },
            separator: if table { need("separator")? } else { String::new() },
            columns: l("columns"),
            dir: if table { None } else { Some(need("dir")?) },
            head: need("head")?,
            tail: s("tail"),
        });
    }
    Ok(views)
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    let mut entries: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(&p, out);
        } else {
            out.push(p);
        }
    }
}

fn rel(root: &Path, p: &Path) -> String {
    p.strip_prefix(root).unwrap_or(p).to_string_lossy().replace('\\', "/")
}

/// Every record file (sorted by path), plus the problems found reading them: files that are not records, and parse
/// errors (`file:line: message`).
pub fn load_records(root: &Path) -> (Vec<Record>, Vec<String>) {
    let mut files = Vec::new();
    walk(&root.join(DIR), &mut files);
    let mut out = Vec::new();
    let mut bad = Vec::new();
    for f in files {
        let r = rel(root, &f);
        let parts: Vec<&str> = r.split('/').collect();
        if r == VIEWS || (parts.get(1) == Some(&"views") && parts.len() == 3 && r.ends_with(".md")) {
            continue;
        }
        let kind = match parts.get(1) {
            Some(&"decisions") if parts.len() == 4 => Some(Kind::Decision),
            Some(&"compat") if parts.len() == 3 => Some(Kind::Compat),
            Some(&"saturation") if parts.len() == 3 => Some(Kind::Saturation),
            Some(&"pending") if parts.len() == 3 => None,
            _ => {
                bad.push(format!("{r}: not a record path (records/decisions/<series>/<id>.toml, records/compat/<id>.toml, records/saturation/<id>.toml, records/pending/<name>.toml, records/views/<view>.head.md|.tail.md, records/views.toml)"));
                continue;
            }
        };
        if !r.ends_with(".toml") {
            bad.push(format!("{r}: a record file ends in .toml"));
            continue;
        }
        let text = match std::fs::read_to_string(&f) {
            Ok(t) => t,
            Err(e) => {
                bad.push(format!("{r}: {e}"));
                continue;
            }
        };
        let entries = match toml::parse(&text) {
            Ok(e) => e,
            Err((l, m)) => {
                bad.push(format!("{r}:{l}: {m}"));
                continue;
            }
        };
        let pending = kind.is_none();
        let id = entries.first().and_then(|e| if let (true, Value::Str(s)) = (e.key == "id", &e.value) { Some(s.as_str()) } else { None });
        let Some(kind) = kind.or_else(|| id.and_then(Kind::of_id)) else {
            bad.push(format!("{r}:1: a pending record starts with `id = \"D-NEW\"`, `\"COMPAT-NEW\"` or `\"SR-NEW\"`"));
            continue;
        };
        out.push(Record { kind, path: r, pending, entries });
    }
    (out, bad)
}

/// The ids of the (non-pending) records of `kind`, sorted. For the readers that only need the id set (trace,
/// compat-ids); they do not validate.
pub fn ids(root: &Path, kind: Kind) -> Vec<String> {
    let mut v: Vec<String> = load_records(root).0.iter().filter(|r| r.kind == kind && !r.pending).map(|r| r.id().to_string()).collect();
    v.sort();
    v
}

/// The `row` cells of the saturation records, with their files.
pub fn saturation_rows(root: &Path) -> Vec<(String, String)> {
    load_records(root).0.into_iter().filter(|r| r.kind == Kind::Saturation && !r.pending).map(|r| (r.str("row").unwrap_or("").to_string(), r.path.clone())).collect()
}

/// Load and validate; the records and views when there is no problem.
fn load_checked(root: &Path) -> Result<(Vec<View>, Vec<Record>), String> {
    let views = load_views(root)?;
    let (records, mut bad) = load_records(root);
    bad.extend(check::validate(root, &views, &records));
    if bad.is_empty() {
        Ok((views, records))
    } else {
        for b in bad.iter().take(60) {
            eprintln!("records: {b}");
        }
        Err(format!("{} problem(s) in records/", bad.len()))
    }
}

/// `cargo xtask records check` and the static check `records`.
pub fn check(root: &Path) -> Result<(), String> {
    let (views, records) = load_checked(root)?;
    let n = |k: Kind| records.iter().filter(|r| r.kind == k && !r.pending).count();
    println!("records: ok: {} decision, {} compat, {} saturation records ({} pending); {} views", n(Kind::Decision), n(Kind::Compat), n(Kind::Saturation), records.iter().filter(|r| r.pending).count(), views.len());
    Ok(())
}

/// Rendered views as (path, text).
type Rendered = Vec<(String, String)>;

/// Every view rendered, and the paths whose file differs from its rendering.
fn stale(root: &Path) -> Result<(Rendered, Vec<String>), String> {
    let (views, records) = load_checked(root)?;
    let rendered = render::render_all(root, &views, &records)?;
    let stale = rendered.iter().filter(|(p, text)| std::fs::read_to_string(root.join(p)).ok().as_deref() != Some(text.as_str())).map(|(p, _)| p.clone()).collect();
    Ok((rendered, stale))
}

/// Whether a train-owned generator (`records-gen`, `kernel-index`) writes the tracked files in place: on the train
/// (`train` is `LIELLA_TRAIN`, `1` there) or with `--in-place`. Anywhere else it writes under [`OUT_OF_TREE`] (D-X.59).
pub fn in_place(args: &[String], train: Option<&str>) -> bool {
    train == Some("1") || args.iter().any(|a| a == "--in-place")
}

/// [`in_place`] with this process's `LIELLA_TRAIN`.
pub fn in_place_env(args: &[String]) -> bool {
    in_place(args, std::env::var("LIELLA_TRAIN").ok().as_deref())
}

/// The directory a train-owned generator writes its tracked-relative paths under: the root in place, else
/// `<root>/target/records-views`.
pub fn out_root(root: &Path, in_place: bool) -> PathBuf {
    if in_place { root.to_path_buf() } else { root.join(OUT_OF_TREE) }
}

/// `cargo xtask records-gen [--check] [--in-place]`. `--check` compares the tracked views whatever `in_place` says;
/// otherwise each view whose file under [`out_root`] differs from its rendering is rewritten there.
pub fn gen_cmd(root: &Path, check_only: bool, in_place: bool) -> Result<(), String> {
    let (rendered, stale) = stale(root)?;
    if check_only {
        for p in &stale {
            eprintln!("{p} is stale: run `cargo xtask records-gen`");
        }
        return if stale.is_empty() { Ok(()) } else { Err(format!("{} view(s) stale", stale.len())) };
    }
    let out = out_root(root, in_place);
    let mut written = 0;
    for (p, text) in &rendered {
        let f = out.join(p);
        if std::fs::read_to_string(&f).ok().as_deref() == Some(text.as_str()) {
            continue;
        }
        if let Some(d) = f.parent() {
            std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
        }
        std::fs::write(&f, text).map_err(|e| format!("{}: {e}", f.display()))?;
        written += 1;
    }
    if in_place {
        println!("records-gen: {} views, {written} rewritten in place", rendered.len());
    } else {
        println!(
            "records-gen: {} views ({} stale in the tree), {written} rewritten under {OUT_OF_TREE}/; read them there. The tracked views are train-owned and untouched (in place: LIELLA_TRAIN=1 or --in-place)",
            rendered.len(),
            stale.len()
        );
    }
    Ok(())
}

/// The static check `records-gen`: stale views are fatal on the train (`LIELLA_TRAIN=1`, which regenerated them just
/// before: a stale view there is a hand edit or a nondeterministic generator); elsewhere one advisory line, because a
/// story branch does not commit views.
pub fn fresh_check(root: &Path) -> Result<(), String> {
    if std::env::var("LIELLA_TRAIN").is_ok_and(|v| v == "1") {
        return gen_cmd(root, true, true);
    }
    let (_, stale) = stale(root)?;
    println!("records-gen: {} views pending regeneration by the train", stale.len());
    Ok(())
}

/// `cargo xtask records <check | fmt [--check] | new ...>`.
pub fn cmd(root: &Path, args: &[String]) -> Result<(), String> {
    match args.first().map(String::as_str) {
        Some("check") => check(root),
        Some("fmt") => fmt(root, args.iter().any(|a| a == "--check")),
        Some("new") => new(root, &args[1..]),
        _ => Err("usage: cargo xtask records <check | fmt [--check] | new <decision|compat|saturation> <id> [--section S] [--series S] [--story S]>".into()),
    }
}

/// The entries in the kind's key order (unknown keys last, so validation names them).
fn canonical(kind: Kind, entries: Vec<toml::Entry>) -> Vec<(String, Value)> {
    let keys = kind.keys();
    let mut e: Vec<(usize, String, Value)> = entries.into_iter().map(|e| (keys.iter().position(|k| *k == e.key).unwrap_or(keys.len()), e.key, e.value)).collect();
    e.sort_by_key(|x| x.0);
    e.into_iter().map(|(_, k, v)| (k, v)).collect()
}

fn fmt(root: &Path, check_only: bool) -> Result<(), String> {
    let mut files = Vec::new();
    walk(&root.join(DIR), &mut files);
    let mut changed = Vec::new();
    for f in files {
        let r = rel(root, &f);
        if !r.ends_with(".toml") || r == VIEWS {
            continue;
        }
        let text = std::fs::read_to_string(&f).map_err(|e| format!("{r}: {e}"))?;
        let entries = toml::parse_lenient(&text).map_err(|(l, m)| format!("{r}:{l}: {m}"))?;
        let id = entries.iter().find(|e| e.key == "id").and_then(|e| if let Value::Str(s) = &e.value { Some(s.clone()) } else { None }).unwrap_or_default();
        let kind = r.split('/').nth(1).and_then(|d| Kind::ALL.into_iter().find(|k| k.dir() == d)).or_else(|| Kind::of_id(&id)).ok_or_else(|| format!("{r}: no kind"))?;
        let out = toml::write(&canonical(kind, entries));
        if out != text {
            changed.push(r.clone());
            if !check_only {
                std::fs::write(&f, out).map_err(|e| format!("{r}: {e}"))?;
            }
        }
    }
    for c in &changed {
        println!("records fmt: {c}{}", if check_only { " is not canonical" } else { " rewritten" });
    }
    if check_only && !changed.is_empty() {
        return Err(format!("{} record(s) not canonical: run `cargo xtask records fmt`", changed.len()));
    }
    Ok(())
}

fn opt<'a>(args: &'a [String], name: &str) -> Option<&'a str> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1)).map(String::as_str)
}

/// `records new <kind> <id> [--section S] [--series S] [--story S]`: a canonical skeleton whose empty values must be
/// filled before `records check` passes. Placeholder ids (`D-NEW`, ...) go to `records/pending/<story>-<k>.toml`.
fn new(root: &Path, args: &[String]) -> Result<(), String> {
    let (Some(kind), Some(id)) = (args.first().and_then(|k| Kind::from_name(k)), args.get(1)) else {
        return Err("usage: records new <decision|compat|saturation> <id> [--section S] [--series S] [--story S]".into());
    };
    let views = load_views(root)?;
    let (records, _) = load_records(root);
    if !id.ends_with("-NEW") && records.iter().any(|r| r.id().eq_ignore_ascii_case(id)) {
        return Err(format!("{id} exists already"));
    }
    let pending = *id == kind.placeholder();
    let parts = schema::parse_id(kind, id);
    if !pending && parts.is_none() {
        return Err(format!("{id} is not a {} id", kind.name()));
    }
    let series = if pending { opt(args, "--series").map(str::to_string) } else { parts.as_ref().map(|p| p.series.clone()) };
    if pending && kind == Kind::Decision && series.is_none() {
        return Err("a D-NEW record needs --series (the series its id will be taken from, e.g. D-10)".into());
    }
    let section = match (kind, opt(args, "--section")) {
        (Kind::Compat, _) => None,
        (_, Some(s)) => Some(s.to_string()),
        (Kind::Decision, None) => series.as_deref().map(schema::default_section),
        (Kind::Saturation, None) => return Err("a saturation record needs --section <1..7>".into()),
    };
    let view = views.iter().find(|v| v.kind == ViewKind::Table(kind) && (kind == Kind::Compat || v.section == section));
    let Some(view) = view else { return Err(format!("no {} view for section {section:?}", kind.name())) };
    let s = |v: &str| Value::Str(v.into());
    let mut e: Vec<(String, Value)> = vec![("id".into(), s(id))];
    if pending && let Some(se) = &series {
        e.push(("series".into(), s(se)));
    }
    if let Some(sec) = &section {
        e.push(("section".into(), s(sec)));
    }
    for c in view.columns.iter().filter(|c| !["id", "body", "status"].contains(&c.as_str())) {
        e.push((c.clone(), s("")));
    }
    e.push(("status".into(), s(kind.statuses()[0])));
    if kind == Kind::Compat {
        e.push(("decisions".into(), Value::List(vec![String::new()])));
    }
    e.push(("story".into(), s(opt(args, "--story").unwrap_or(""))));
    e.push(("date".into(), s("")));
    e.push(("body".into(), Value::Body(String::new())));
    let text = toml::write(&canonical(kind, e.into_iter().map(|(key, value)| toml::Entry { key, value, line: 0 }).collect()));
    let path = if pending {
        let stem = opt(args, "--story").unwrap_or("new").to_string();
        let k = (1..).find(|k| !root.join(format!("{DIR}/pending/{stem}-{k}.toml")).exists()).unwrap_or(1);
        format!("{DIR}/pending/{stem}-{k}.toml")
    } else if kind == Kind::Decision {
        format!("{DIR}/decisions/{}/{id}.toml", series.unwrap_or_default())
    } else {
        format!("{DIR}/{}/{id}.toml", kind.dir())
    };
    let p = root.join(&path);
    if p.exists() {
        return Err(format!("{path} exists already"));
    }
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
    }
    std::fs::write(&p, text).map_err(|e| format!("{path}: {e}"))?;
    println!("records new: wrote {path}; fill every empty value (story, date, the view's columns, body), then `cargo xtask records check`");
    Ok(())
}

/// For the tests: a map of path -> text written under a fresh directory.
#[cfg(test)]
fn tree(files: &[(&str, &str)]) -> PathBuf {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static N: AtomicUsize = AtomicUsize::new(0);
    let d = std::env::temp_dir().join(format!("xtask-records-{}-{}", std::process::id(), N.fetch_add(1, Ordering::Relaxed)));
    let _ = std::fs::remove_dir_all(&d);
    for (p, t) in files {
        let f = d.join(p);
        std::fs::create_dir_all(f.parent().expect("parent")).expect("mkdir");
        std::fs::write(f, t).expect("write");
    }
    d
}

