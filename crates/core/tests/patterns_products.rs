/// The output's sections, by name, in order.
fn sections(text: &str) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    for l in text.lines() {
        if let Some(name) = l.strip_prefix("== ") {
            out.push((name.to_string(), Vec::new()));
        } else if let Some(s) = out.last_mut() {
            s.1.push(l.to_string());
        }
    }
    out
}

fn section<'a>(all: &'a [(String, Vec<String>)], name: &str) -> &'a [String] {
    all.iter().find(|(n, _)| n == name).map_or(&[], |(_, v)| v.as_slice())
}

