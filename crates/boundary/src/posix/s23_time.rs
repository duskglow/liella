// `stime` is a compat-only symbol: `stime@GLIBC_2.2.5`, no default version in 2.39. Old binaries
// resolve it in `libc.so.6`; a program linked anew (static or dynamic) must not find it, so the
// translation is exported under an internal name and a `.symver` stub
// (`csys/src/machine/compat_aliases.S`, generated by `cargo xtask compat-gen`) gives it the non-default version (single `@`; the stub's symbol is named `stime@GLIBC_2.2.5`, which no `stime`
// reference matches in `libc.a`). Tests call it as the plain Rust function (D-27.4).
crate::internal_entry! {
/// `stime`'s translation, exported only as `stime@GLIBC_2.2.5` (compat-only; see above).
pub extern "C" fn liella_compat_stime(t: Option<&i64>) -> c_int {
    ret::zero(conv::req(t).and_then(|t| clock_compat::stime(&CSys, conv::copy(t))))
}}

