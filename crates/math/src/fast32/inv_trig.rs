#[cfg(test)]
pub(super) const ASIN_BOUND: f64 = 10.4;
#[cfg(test)]
pub(super) const ATAN2_BOUND: f64 = 10.7;
/// atanf: ε ≤ 7.0u. 16 keeps a margin of more than 2.
pub(super) const ATAN_DELTA: u64 = 16;
/// asinf, acosf: ε ≤ 10.4u.
pub(super) const ASIN_DELTA: u64 = 24;
/// atan2f: ε ≤ 10.7u.
pub(super) const ATAN2_DELTA: u64 = 32;
/// The odd minimax polynomial for atan on [-1/64, 1/64] (`crates/math/fits/fast32_atan.fit`,
