/// Lines that depend on the environment the job runs in, not on the C library under test: the
/// section, the alternative line, the recorded line it is read as, and why. `env_norm` applies
/// this table to BOTH the reference's and Liella's output (Liella's glob follows the same login
/// fallback when HOME is set and empty), so the test checks that the two agree after
/// normalisation. Keep it tiny: only lines shown to flip with the job's login environment.
const REFERENCE_ENV: &[(&str, &str, &str, &str)] = &[(
    r##"glob"##,
    r##"glob [~/x] NOCHECK|TILDE -> 0 pathc=1 offs=0 magchar=0 [<home>/x] $"##,
    r##"glob [~/x] NOCHECK|TILDE -> 0 pathc=1 offs=0 magchar=0 [~/x] $"##,
    "`~/x` with HOME set and empty: whether the reference falls back to the login user's home varies with the environment of the job (keke gates 2026-10-11: <home>/x in two jobs, [~/x] in others and in the record; same source, no Liella code in the reference process)",
)];

/// Rewrites every `REFERENCE_ENV` alternative line in `out` to its recorded line.
fn env_norm(out: &mut [(String, Vec<String>)]) {
    for (name, lines) in out.iter_mut() {
        for l in lines.iter_mut() {
            if let Some(&(_, _, recorded, _)) = REFERENCE_ENV.iter().find(|(s, alt, _, _)| *s == name.as_str() && *alt == l.as_str()) {
                *l = recorded.to_string();
            }
        }
    }
}

